		private void UpdateVariance ( )
		{
			string quantity = string.Empty;

			if (quantityTextBox.Enabled && string.IsNullOrEmpty ( quantityTextBox.Text ) == false)
			{
				quantity = quantityTextBox.Text;
			}
			else if (quantityTextBox2.Enabled && string.IsNullOrEmpty ( quantityTextBox2.Text ) == false)
			{
				quantity = quantityTextBox2.Text;
			}

			if (fillStandRequestTypeComboBox.SelectedItem as string == "Partial Fill"
				|| fillStandRegistrationIDComboBox.SelectedValue == null
				|| string.IsNullOrEmpty ( quantity ))
			{
				differentialPressureAndVarianceTextBox.Text = "";
				return;
			}

			FMChannelFactory<IEquipments> equipClient = new FMChannelFactory<IEquipments> ( );
			IEquipments equipments = equipClient.CreateProxy ( );

			EquipmentClass equipment = equipments.GetBySite(security, (Guid)fillStandRegistrationIDComboBox.SelectedValue, site);

			double equipmentCapacity = 0.0;
			double equipmentVolume = 0.0;
			double volume = 0.0;

			try
			{
				equipmentCapacity = System.Convert.ToDouble ( equipment.Capacity );
			}
			catch
			{
				MessageBox.Show ( this, "Invalid equipment capacity", this.Text );
				differentialPressureAndVarianceTextBox.Text = "";
				return;
			}

			try
			{
				equipmentVolume = System.Convert.ToDouble ( equipment.Volume );
			}
			catch
			{
				MessageBox.Show ( this, "Invalid equipment volume", this.Text );
				differentialPressureAndVarianceTextBox.Text = "";
				return;
			}

			try
			{
				if (string.IsNullOrEmpty ( quantity ) == false)
				{
					volume = System.Convert.ToDouble ( quantity );
				}
			}
			catch
			{
				MessageBox.Show ( this, "Invalid quantity", this.Text );
				differentialPressureAndVarianceTextBox.Text = "";
				return;
			}

			double variance = 0.0;

			if (transaction == null
				|| transaction.Number01 == null
				|| ( transaction.LineItems[0] as LineItemDO ).Quantity == null)
			{

				if (fillStandRequestTypeComboBox.SelectedItem as string == "Return To Bulk")
				{
					variance = volume - equipmentVolume;
				}
				else
				{
					// if the volume added will fill above capacity then we do a different calculation
					if (( equipmentVolume + volume ) > equipmentCapacity)
					{
						variance = equipmentCapacity - ( equipmentVolume + volume );
					}
					else
					{
						variance = ( equipmentCapacity - equipmentVolume ) - volume;
					}
				}
			}

			else
			{
				variance = transaction.Number01.Value;
				double previousVolume = ( transaction.LineItems[0] as LineItemDO ).Quantity.Gross;

				variance += volume - previousVolume;
			}

			differentialPressureAndVarianceTextBox.Text = variance.ToString ( site.GetNumberFormatInfo ( SITE_VARIABLE_TYPE.VOLUME ) );
		}

