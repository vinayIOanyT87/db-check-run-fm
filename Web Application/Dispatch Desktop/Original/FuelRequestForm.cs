				fuelRequestRequestCancelledCheckBox.Checked = false;
				fuelRequestRequestCancelledCheckBox.Enabled = false;
				fillStandRequestCancelledCheckBox.Checked = false;
				fillStandRequestCancelledCheckBox.Enabled = false;
