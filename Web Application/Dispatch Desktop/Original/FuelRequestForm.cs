		private void SaveTransaction ( )
		{
			FMChannelFactory<ICompanies> companiesClient = new FMChannelFactory<ICompanies> ( );
			ICompanies companies = companiesClient.CreateProxy ( );

			FMChannelFactory<ISites> sitesClient = new FMChannelFactory<ISites> ( );
			ISites sites = sitesClient.CreateProxy ( );

			if (transaction == null)
			{
				SiteTimeConverter timeConverter = new SiteTimeConverter ( site );

				transaction = new TransactionDO ( );
				transaction.LineItems.Add ( new LineItemDO ( ) );
				transaction.TransID = FuelsManagerId.NewId ( );
				transaction.Site = security.SiteID;
				transaction.SiteGuid = security.SiteGuid;
				transaction.Alias = transactionAlias.ID;
				transaction.TransTypeID = transactionAlias.TransTypeID;
				transaction.TransactionAliasGuid = transactionAlias.IdentityGuid;
				transaction.DocumentNumber = sites.GetNextDocumentNumber ( security, DOCUMENT_TYPE.MANUAL_BOL, security.SiteGuid );

				InventoryDateSR inventoryDateSR = new InventoryDateSR ( );
				inventoryDateSR.Security = Security;
				inventoryDateSR.CurrentSiteGuid = Security.SiteGuid;

				FMChannelFactory<IInventoryDateProcessor> invDateProcessorClient = new FMChannelFactory<IInventoryDateProcessor> ( );
				IInventoryDateProcessor invDateProcessor = invDateProcessorClient.CreateProxy ( );
				InventoryDateDO inventoryDateDO = invDateProcessor.Process ( inventoryDateSR );

				transaction.InventoryDate = inventoryDateDO.InventoryDate;
				transaction.TransactionDateTime = timeConverter.Now ( );
				transaction.OriginApplication = TransactionOrigin.Dispatch;

				if (requestType == REQUEST_TYPE.RequestFuel
					|| requestType == REQUEST_TYPE.Transient
					|| requestType == REQUEST_TYPE.FillStand)
				{
					transaction.Status = TransactionStatus.Requested;
					foreach (LineItemDO LineItem in transaction.LineItems)
					{
						LineItem.Status = TransactionStatus.Requested;
					}

					transaction.RequestedDateTime = timeConverter.Now ( );
				}
				else
				{
					transaction.Status = TransactionStatus.Completed;
					foreach (LineItemDO LineItem in transaction.LineItems)
					{
						LineItem.Status = TransactionStatus.Completed;
					}

					transaction.RequestedDateTime = timeConverter.Now ( );
					transaction.TimeOut = timeConverter.Now ( );
				}


				List<CompanyClass> managerCollection = companies.EnumerateByRole ( security, COMPANY_ROLE.MANAGER, false, true );
				if (managerCollection.Count == 0)
					throw new Exception ( "No Manager" );

				if (managerCollection.Count > 1)
					throw new Exception ( "Multiple Managers" );

				transaction.ManagerID = managerCollection[0].ID;
				transaction.ManagerCode = managerCollection[0].Code;
				transaction.ManagerCompanyGuid = managerCollection[0].IdentityGuid;

				List<CompanyClass> ownerCollection = companies.EnumerateByRole ( security, COMPANY_ROLE.OWNER, false, true );
				if (ownerCollection.Count == 0)
					throw new Exception ( "No Owner" );

				if (ownerCollection.Count > 1)
					throw new Exception ( "Multiple Owners" );

				transaction.OwnerID = ownerCollection[0].ID;
				transaction.OwnerCode = ownerCollection[0].Code;
				transaction.OwnerCompanyGuid = ownerCollection[0].IdentityGuid;
				transaction.Number02 = System.Convert.ToDouble ( requestType );

			}
			if (TransactionWillBeSetToCompleted == true)
			{
				SiteTimeConverter timeConverter = new SiteTimeConverter ( site );
				transaction.Status = TransactionStatus.Completed;
				foreach (LineItemDO LineItem in transaction.LineItems)
				{
					LineItem.Status = TransactionStatus.Completed;
				}

				transaction.RequestedDateTime = timeConverter.Now ( );
				transaction.TimeOut = timeConverter.Now ( );
			}

			if (fuelingServiceRequestTabControl.TabPages.Contains ( fillStandTabPage ))
				SaveFillStandTransaction ( );
			else
				SaveFuelRequestTransaction ( );

			DateTime requestedDate = requestDateDateTimePicker.Value;
			DateTime requestedTime = requestDateTimePicker.Value;
			DateTime requestedDateTime = new DateTime ( requestedDate.Year, requestedDate.Month, requestedDate.Day, requestedTime.Hour, requestedTime.Minute, requestedTime.Second );

			transaction.RequestedDateTime = requestedDateTime;

			if (!ignoreDispatchTimeCheckBox.Checked)
			{
				if (transaction.Status == TransactionStatus.Dispatched
				|| transaction.Status == TransactionStatus.Arrived
				|| transaction.Status == TransactionStatus.Started
				|| transaction.Status == TransactionStatus.Stopped
				|| transaction.Status == TransactionStatus.Completed)
				{
					transaction.DispatchedDateTime = DispatchdatePicker.Value.Date + dispatchDateTimePicker.Value.TimeOfDay;
				}
			}
			else
				transaction.DispatchedDateTime = null;

			if (!ignoreArrivalTimeCheckBox.Checked)
			{
				if (transaction.Status == TransactionStatus.Arrived
				|| transaction.Status == TransactionStatus.Started
				|| transaction.Status == TransactionStatus.Stopped
				|| transaction.Status == TransactionStatus.Completed)
					transaction.TimeIn = ArrivaldatePicker.Value.Date + arrivalDateTimePicker.Value.TimeOfDay;
			}
			else
				transaction.TimeIn = null;

			if (!ignoreStartTimeCheckBox.Checked)
			{
				if (transaction.Status == TransactionStatus.Started
				|| transaction.Status == TransactionStatus.Stopped
				|| transaction.Status == TransactionStatus.Completed)
					transaction.RouteSchedule.FST = StartdatePicker.Value.Date + startDateTimePicker.Value.TimeOfDay;
			}
			else
				transaction.RouteSchedule.FST = null;

			if (!ignoreStopTimeCheckBox.Checked)
			{
				if (transaction.Status == TransactionStatus.Stopped
				|| transaction.Status == TransactionStatus.Completed)
					transaction.TimeEnd = StopdatePicker.Value.Date + stopDateTimePicker.Value.TimeOfDay;
			}
			else
				transaction.TimeEnd = null;

			if (transaction.Status == TransactionStatus.Completed)
				transaction.TimeOut = CompletiondatePicker.Value.Date + completionDateTimePicker.Value.TimeOfDay;

			if (transaction.Alias == fuelRequestTransactionAlias)
			{
				( transaction.LineItems[0] as LineItemDO ).Quantity.Gross *= -1;
				( transaction.LineItems[0] as LineItemDO ).Quantity.Net *= -1;
			}

			FMChannelFactory<IEquipments> equipClient = new FMChannelFactory<IEquipments> ( );
			IEquipments equipments = equipClient.CreateProxy ( );

			LineItemDO lineItem = ( transaction.LineItems[0] as LineItemDO );
			EquipmentClass fillstandEquipment = null;

			// if this is a rtb then the sourceeq gets set and the destinationeq will be blank
			bool ThisIsARTB = fillStandRequestTypeComboBox.SelectedItem as string == "Return To Bulk" ? true : false;

			bool ThirdConsequtivePromptIssueAndPassed = false;
			int Current_Consecutive_OOS_Variance = 0;	// used to determine if we need to tell the user again
			// we only check the variance on a fillstand and rtb the first time the data is entered. If we are editing the record then
			// we do not check the variance even if the operator has chenged the quantity


			//good
			if (( requestType == REQUEST_TYPE.FillStand || 
				requestType == REQUEST_TYPE.FastLogFillStand && 
				string.IsNullOrEmpty ( transaction.Notes ) ) && 
				(string) fillStandRequestTypeComboBox.SelectedItem != "Partial Fill" &&
				transaction.Status != TransactionStatus.Cancelled &&
				TransactionInitialyCompleted == false)
			{
				fillstandEquipment = new EquipmentClass ( ); // delete this line - no needed
				fillstandEquipment = null;

				if (ThisIsARTB == false)
					fillstandEquipment = equipments.GetBySite(Security, lineItem.DestinationEQ.EquipmentGuid, site);
				else if (ThisIsARTB == true)	// rtb
					fillstandEquipment = equipments.GetBySite(Security, lineItem.SourceEQ.EquipmentGuid, site);

				Current_Consecutive_OOS_Variance = fillstandEquipment.Consecutive_OOS_Variance;

				if (fillstandEquipment != null)
				{
					double safeFill = Convert.ToDouble ( fillstandEquipment.SafeFill );
					double volume = Convert.ToDouble ( fillstandEquipment.Volume );

					double localVariance = 0.0;
					double Tolerance = 0.0;

					if (ThisIsARTB == true)
					{
						localVariance = lineItem.Quantity.NetInventoryChange - volume;
						Tolerance = Math.Abs ( localVariance / volume * 100.0 );
					}
					else
					{
						// if the volume added will fill above capacity then we do a different calculation
						if (( lineItem.Quantity.NetInventoryChange + volume ) > safeFill)
						{
							localVariance = safeFill - ( lineItem.Quantity.NetInventoryChange + volume );
						}
						else
						{
							localVariance = ( safeFill - volume ) - lineItem.Quantity.NetInventoryChange;
						}
						Tolerance = Math.Abs ( localVariance / safeFill * 100.0 );
					}
					// verify that the variance has not changed direction before issueing the message

					if (( fillstandEquipment.Consecutive_OOS_Variance == -2 && localVariance < 0 )
						|| ( fillstandEquipment.Consecutive_OOS_Variance == 2 && localVariance > 0 ))
					{
						// Check the tolerance - if we will be at three once we save the transaction, we need to
						// require a comment.
						if (Tolerance >= 2 &&
					 ( string.IsNullOrEmpty ( transaction.Notes ) ||
							LastTransactionMemo.ToUpper ( ) == transaction.Notes.ToUpper ( ) ))
						{
							LastTransactionMemo = transaction.Notes;
							if (requestType == REQUEST_TYPE.FillStand
								|| requestType == REQUEST_TYPE.FastLogFillStand)
							{
								fuelingServiceRequestTabControl.SelectedTab = fillStandTabPage;
								fillStandCommentTextBox.Focus ( );
							}
							throw new ApplicationException ( DeviationCommentRequiredMessage );
						}
						else
							ThirdConsequtivePromptIssueAndPassed = true;
					}
				}
			}
			transaction.UserData[TransactionDO.USER_DATA_KEY_04] = serialnumbertextBox.Text;
			transaction.IssuePoint = isspttextBox.Text;
			transaction.IssuePointNumber = issptnumtextBox.Text;
			if (!string.IsNullOrEmpty ( grossgaltextBox.Text ))
				transaction.Number03 = System.Convert.ToDouble ( grossgaltextBox.Text );

			base.SaveTransaction ( transaction );

			if (transaction.TransactionGuid == Guid.Empty)
			{
				TransactionDO LocalTransaction = base.GetTransaction ( transaction.TransID );
				transaction.TransactionGuid = LocalTransaction.TransactionGuid;
			}

			LastTransactionMemo = string.Empty;

			// Check the variance - we need a warning message if this is the first occurance of a variance
			// over 2%.  This must be done after the transaction has been saved since the variance count
			// is calculated by a trigger on the line item table.
			// if this is a rtb then the sourceeq gets set and the destinationeq will be blank
			if (( ThirdConsequtivePromptIssueAndPassed == false &&
					( requestType == REQUEST_TYPE.FillStand ||
					requestType == REQUEST_TYPE.FastLogFillStand ) )
				&& (string) fillStandRequestTypeComboBox.SelectedItem != "Partial Fill" &&
				transaction.Status != TransactionStatus.Cancelled &&
				TransactionInitialyCompleted == false)
			{
				fillstandEquipment = null;
				if (ThisIsARTB == false)
					fillstandEquipment = equipments.GetBySite(Security, lineItem.DestinationEQ.EquipmentGuid, site);
				else if (ThisIsARTB == true)	// rtb
					fillstandEquipment = equipments.GetBySite(Security, lineItem.SourceEQ.EquipmentGuid, site);

				if (fillstandEquipment != null)
				{
					if (Current_Consecutive_OOS_Variance != fillstandEquipment.Consecutive_OOS_Variance)
					{
						int CheckInterval = ( fillstandEquipment.Consecutive_OOS_Variance % 3 );

						if (CheckInterval == 1
							|| CheckInterval == -1)
						{
							// First occurrence of 2% loss.  First occurrence of 2% gain.
							string message = string.Format ( "First occurrence of 2% {0}.", ( CheckInterval > 0 ) ? "gain" : "loss" );

							MessageBox.Show ( this, message, "Dispatch", MessageBoxButtons.OK );
							SaveTransactionNote ( transaction.TransactionGuid, message, transaction.Notes );

						}
						else if (CheckInterval == 2
							|| CheckInterval == -2)
						{
							string message = string.Format ( "Second occurrence of 2% {0}.", ( fillstandEquipment.Consecutive_OOS_Variance > 0 ) ? "gain" : "loss" );

							MessageBox.Show ( this, message, "Dispatch", MessageBoxButtons.OK );

							SaveTransactionNote ( transaction.TransactionGuid, message, transaction.Notes );

						}
					}
				}

			}

			if (transaction.Alias == fuelRequestTransactionAlias)
			{
				( transaction.LineItems[0] as LineItemDO ).Quantity.Gross *= -1;
				( transaction.LineItems[0] as LineItemDO ).Quantity.Net *= -1;
			}
		}

