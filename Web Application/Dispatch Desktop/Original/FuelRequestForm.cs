					// If we did not find the equipment in the list, we still want it to show up.  So, go
					// get the equipment and add it to the list
					if (selectedItem == null)
					{
						EquipmentClass equipment = equipments.GetBySite(Security, equipmentDO.EquipmentGuid, site);
						if (equipment.IdentityGuid == equipmentDO.EquipmentGuid)
						{
							equipmentCollection.Add ( equipment );
							selectedItem = equipment;
						}
					}
				}
			}

			// sort the collection
			var sortedCollection = from E in equipmentCollection
								   orderby E.ID
								   select E;

			List<EquipmentClass> sortedEquipmentCollection = new List<EquipmentClass> ( );
			foreach (var E in sortedCollection)
			{
				sortedEquipmentCollection.Add ( E );
			}

			detailRegistrationIDComboBox.DisplayMember = "ID";
			detailRegistrationIDComboBox.DataSource = sortedEquipmentCollection;

			if (selectedItem != null)
				detailRegistrationIDComboBox.SelectedItem = selectedItem;
			else
				detailRegistrationIDComboBox.SelectedIndex = -1;

			if (fuelingServiceRequestTabControl.TabPages.Contains ( fillStandTabPage ))
			{
				if (transactionAlias.AutoCreateReferenceData
				&& ConfigurationManager.AppSettings["AutoCreateSourceEquipmentData"] == "true")
				{
					fillStandRefCodeComboBox.DropDownStyle = ComboBoxStyle.DropDown;
					fillStandRegistrationIDComboBox.DropDownStyle = ComboBoxStyle.DropDown;
				}
				else
				{
					fillStandRefCodeComboBox.DropDownStyle = ComboBoxStyle.DropDownList;
					fillStandRegistrationIDComboBox.DropDownStyle = ComboBoxStyle.DropDownList;
				}

				// sort by ref code
				var sortedList = from E in sortedEquipmentCollection
								 orderby E.Xref
								 select E;

				List<EquipmentClass> sortedByXRef = new List<EquipmentClass> ( );
				foreach (var E in sortedList)
				{
					sortedByXRef.Add ( E );
				}

				fillStandRefCodeComboBox.DataSource = sortedByXRef;
				fillStandRegistrationIDComboBox.DataSource = sortedEquipmentCollection;

				if (selectedItem != null)
				{
					fillStandRefCodeComboBox.SelectedItem = selectedItem;
					fillStandRegistrationIDComboBox.SelectedItem = selectedItem;
					typeTextBox.Text = selectedItem.TypeClass;
				}
				else
				{
					fillStandRefCodeComboBox.SelectedIndex = -1;
					fillStandRegistrationIDComboBox.SelectedIndex = -1;
