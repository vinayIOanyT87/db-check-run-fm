			if (requestType != REQUEST_TYPE.FastLogFillStand
			&& requestType != REQUEST_TYPE.FillStand)
			{
				FUELING_TYPES fuelingType = ( source ) ? FUELING_TYPES.REFUELER : FUELING_TYPES.DEFUELER;
				for (int Index = equipmentCollection.Count - 1; Index >= 0; --Index)
				{
					EquipmentClass equipment = equipmentCollection[Index];
					if (equipment.FuelingType != fuelingType)
					{
						equipmentCollection.RemoveAt ( Index );
					}
				}
			}

			// Set the style of the drop down based on whether we need to allow manual entry
			if (transactionAlias.AutoCreateReferenceData
			&& ConfigurationManager.AppSettings["AutoCreateSourceEquipmentData"] == "true")
				detailRegistrationIDComboBox.DropDownStyle = ComboBoxStyle.DropDown;
			else
				detailRegistrationIDComboBox.DropDownStyle = ComboBoxStyle.DropDownList;

			// If there is a selected item, make sure it is in the list even if it does
			// not meet the criteria.  The user may have dispatched the equipment despite
			// warnings about the equipment not meeting the request parameters.
			if (selectedItem != null)
			{
				if (equipmentCollection.Find ( x => x.Index == selectedItem.Index ) == null)
				{
					equipmentCollection.Add ( selectedItem );
				}
			}
			else if (transaction != null)
			{
