		private void PopulateAircraftIDComboBox ( )
		{
			EquipmentClass selectedItem = aircraftIDComboBox.SelectedItem as EquipmentClass;

			object fuelCardIndex = null;

			if (activityComboBox.SelectedValue != null
				&& typeof ( int ).IsInstanceOfType ( activityComboBox.SelectedValue )
				&& (int) activityComboBox.SelectedValue != 0)
			{
				fuelCardIndex = activityComboBox.SelectedValue;
			}

			EQUIPMENT_TYPE[] types = transactionAlias.GetEquipmentTypes ( true, 1 );

			FMChannelFactory<IEquipments> equipClient = new FMChannelFactory<IEquipments> ( );
			IEquipments equipments = equipClient.CreateProxy ( );

			if (fuelRequestGradeComboBox.SelectedValue != null
				&& typeof ( int ).IsInstanceOfType ( fuelRequestGradeComboBox.SelectedValue )
				&& (int) fuelRequestGradeComboBox.SelectedValue != 0)
			{
				int productIndex = (int) fuelRequestGradeComboBox.SelectedValue;


				DataSet set = equipments.EnumerateByTypesCompanyFuelCardProductAndSecondaryStorage1 ( security, types, null, fuelCardIndex, 0, null );
				EquipmentClass Equipment = new EquipmentClass ( );

				if (set != null && set.Tables != null && set.Tables.Count != 0)
				{
					while (set.Tables[0].Rows.Count != 0)
					{
						Equipment = new EquipmentClass ( );
						Equipment.Load ( set );
						equipmentCollection.Add ( Equipment );
						set.Tables[0].Rows.RemoveAt ( 0 );
					}
				}


				DataSet set1 = equipments.EnumerateByTypesCompanyFuelCardProductAndSecondaryStorage1 ( security, types, null, fuelCardIndex, productIndex, null );
				List<EquipmentClass> productSpecificEquimentCollection = new List<EquipmentClass> ( );

				if (set1 != null && set1.Tables != null && set1.Tables.Count != 0)
				{
					while (set1.Tables[0].Rows.Count != 0)
					{
						Equipment = new EquipmentClass ( );
						Equipment.Load ( set1 );
						productSpecificEquimentCollection.Add ( Equipment );
						set1.Tables[0].Rows.RemoveAt ( 0 );
					}
				}


				foreach (EquipmentClass equipment in productSpecificEquimentCollection)
				{
					equipmentCollection.Add ( equipment );
				}
			}
			else
			{
				DataSet set = equipments.EnumerateByTypesCompanyFuelCardProductAndSecondaryStorage1 ( security, types, null, fuelCardIndex, null, null );
				EquipmentClass Equipment = new EquipmentClass ( );

				if (set != null && set.Tables != null && set.Tables.Count != 0)
				{
					while (set.Tables[0].Rows.Count != 0)
					{
						Equipment = new EquipmentClass ( );
						Equipment.Load ( set );
						equipmentCollection.Add ( Equipment );
						set.Tables[0].Rows.RemoveAt ( 0 );
					}
				}
			}

			if (transactionAlias.AutoCreateReferenceData && ConfigurationManager.AppSettings["AutoCreateDestinationEquipmentData"] == "true")
			{
				fuelRequestRefCodeComboBox.DropDownStyle = ComboBoxStyle.DropDown;
				aircraftIDComboBox.DropDownStyle = ComboBoxStyle.DropDown;
			}
			else
			{
				fuelRequestRefCodeComboBox.DropDownStyle = ComboBoxStyle.DropDownList;
				aircraftIDComboBox.DropDownStyle = ComboBoxStyle.DropDownList;
			}

			if (selectedItem != null)
			{
				selectedItem = equipmentCollection.Find ( x => x.Index == selectedItem.Index );
			}
			else if (transaction != null)
			{
				EquipmentDO equipmentDO = ( transaction.Alias == fuelRequestTransactionAlias ) ? transaction.DestinationEQ1 : transaction.SourceEQ1;
				// if the user did not add it to the database no record will be returned just set the text
				if (equipmentDO.EquipmentGuid == Guid.Empty)
				{
					if (aircraftIDComboBox.Text.Length == 0)
					{
						aircraftIDComboBox.Text = equipmentDO.RegistrationID;
					}

					if (fuelRequestRefCodeComboBox.Text.Length == 0)
					{
						fuelRequestRefCodeComboBox.Text = transaction.UserData18;
					}
				}
				else
				{
					selectedItem = equipmentCollection.Find(x => x.IdentityGuid == equipmentDO.EquipmentGuid);
				}
			}

			string FuelRequestEnteredText = "";
			string AircraftEnteredText = "";

			FuelRequestEnteredText = fuelRequestRefCodeComboBox.Text;
			AircraftEnteredText = aircraftIDComboBox.Text;

			// we need to reset the combo box parameters each time to preclude a malfunction.
			// If the datasource has no items in the collection the display member and value member will be reset
			fuelRequestRefCodeComboBox.DataSource = null;
			fuelRequestRefCodeComboBox.Items.Clear ( );
			fuelRequestRefCodeComboBox.DisplayMember = "XRef";
			fuelRequestRefCodeComboBox.ValueMember = "Index";
			aircraftIDComboBox.DataSource = null;
			aircraftIDComboBox.Items.Clear ( );
			aircraftIDComboBox.DisplayMember = "ID";
			aircraftIDComboBox.ValueMember = "Index";

			// Only add unique Xrefs to the combo
			var sortedCollection = from E in equipmentCollection
								   orderby E.Xref
								   select E;

			List<EquipmentClass> filteredCollection = new List<EquipmentClass> ( );
			foreach (EquipmentClass aircraft in sortedCollection)
			{
				if (FindXREF ( filteredCollection, aircraft.Xref ) == false)
				{
					filteredCollection.Add ( aircraft );
				}
			}

			fuelRequestRefCodeComboBox.DataSource = filteredCollection;
			aircraftIDComboBox.DataSource = equipmentCollection;

			if (selectedItem != null)
			{
				fuelRequestRefCodeComboBox.Text = selectedItem.Xref;
				aircraftIDComboBox.SelectedItem = selectedItem;
			}
			else
			{
				fuelRequestRefCodeComboBox.SelectedIndex = -1;
				aircraftIDComboBox.SelectedIndex = -1;
			}

			// if after the reload there is no selection but the user had entered text restore it here
			if (fuelRequestRefCodeComboBox.SelectedIndex == -1 && FuelRequestEnteredText.Length > 0)
			{
				fuelRequestRefCodeComboBox.Text = FuelRequestEnteredText;
			}

			if (aircraftIDComboBox.SelectedIndex == -1 && AircraftEnteredText.Length > 0)
			{
				aircraftIDComboBox.Text = AircraftEnteredText;
			}
		}

		private bool FindXREF ( List<EquipmentClass> filteredCollection, string xRef )
		{
			foreach (EquipmentClass Equipment in filteredCollection)
			{
				if (Equipment.Xref.Equals ( xRef ))
				{
					return true;
				}
			}

			return false;

		}

		private void PopulateGradeComboBox ( )
		{
			ComboBox comboBox = ( fuelingServiceRequestTabControl.TabPages.Contains ( fillStandTabPage ) ) ? fillStandGradeComboBox : fuelRequestGradeComboBox;

			ProductClass selectedItem = comboBox.SelectedItem as ProductClass;

			FMChannelFactory<IProducts> productsClient = new FMChannelFactory<IProducts> ( );
