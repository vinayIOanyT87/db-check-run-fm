		private bool VerifyAircfartSetupIsCorrect ( )
		{
			FMChannelFactory<IEquipments> equipClient = new FMChannelFactory<IEquipments> ( );
			IEquipments equipments = equipClient.CreateProxy ( );

			// check if a fueladditive is required and is selected
			// if not prompt the user for confirmation
			if (requestType == REQUEST_TYPE.FastLog)
			{
				if (aircraftIDComboBox.SelectedValue != null
					&& typeof ( int ).IsInstanceOfType ( aircraftIDComboBox.SelectedValue )
					&& (int) aircraftIDComboBox.SelectedValue != 0)
				{
					EquipmentClass equipmentaircraft = equipments.GetBySite(security, (Guid)aircraftIDComboBox.SelectedValue, site);

					if (equipmentaircraft != null &&
						detailRegistrationIDComboBox.Text != null &&
						detailRegistrationIDComboBox.Text != "")
					{
						Guid equipmentGuid = equipments.GetIdentityGuid(security, detailRegistrationIDComboBox.Text);
						if (equipmentGuid != Guid.Empty)
						{
							EquipmentClass equipment = equipments.GetBySite(security, equipmentGuid, site);
							if (equipment != null &&
								equipment.FuelingType == FUELING_TYPES.REFUELER)
							{
								if (equipment.FuelAdditiveFlag == false &&
									equipmentaircraft.FuelAdditiveFlag == true)
								{
									DialogResult result = MessageBox.Show ( this,
										"Attention, The Aircraft requires a fuel additive but the Refueler does not have the additive. Create transaction anyway?",
										"Fastlog",
										MessageBoxButtons.YesNo,
										MessageBoxIcon.Warning );

									if (result == DialogResult.No)
									{
										return false;
									}
								}
							}
						}
					}
				}
			}
			return true;
		}

		private bool VerifyVolumeIsCorrect ( )
		{
			if (fuelRequestRequestTypeComboBox.SelectedItem as string == "Refuel" ||
				fuelRequestRequestTypeComboBox.SelectedItem as string == "Defuel")
			{
				// The quantityTextBox will be enabled at this point when we are completing an item.  Before we are
				// completing a request the quantity may remain zero (and in fact may have to since the textbox is
				// disabled.
				if (quantityTextBox.Enabled)
				{
					double Quantity = System.Convert.ToDouble ( quantityTextBox.Text.DefaultIfNullOrEmpty ( "0" ) );
					if (Quantity <= 0.0)
					{
						MessageBox.Show ( "Transaction can not be saved with a quantity of zero." );
						fuelingServiceRequestTabControl.SelectedTab = detailTabPage;
						quantityTextBox.Focus ( );
						return false;
					}
				}
			}
			return true;
		}

