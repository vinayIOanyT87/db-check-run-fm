			ProductCollectionClass productCollection = new ProductCollectionClass ( );

			DataSet Set = products.EnumerateByType1 ( security, PRODUCT_TYPE.COMPONENT_PRODUCT );

			DataTable Table = Set.Tables[0];
			ProductClass Product = new ProductClass ( );

			while (Table.Rows.Count != 0)
			{
				Product = new ProductClass ( site );
				Product.Load ( Set );
				productCollection.Add ( Product );
				Table.Rows.RemoveAt ( 0 );
			}

			if (transactionAlias.AutoCreateReferenceData
			&& ConfigurationManager.AppSettings["AutoCreateProductData"] == "true")
				comboBox.DropDownStyle = ComboBoxStyle.DropDown;
			else
				comboBox.DropDownStyle = ComboBoxStyle.DropDownList;

			if (selectedItem != null)
				selectedItem = productCollection.Find(x => x.IdentityGuid == selectedItem.IdentityGuid);
			else if (transaction != null)
				selectedItem = productCollection.Find(x => x.IdentityGuid == (transaction.LineItems[0] as LineItemDO).ProductGuid);

			comboBox.DataSource = productCollection;

			if (selectedItem != null)
				comboBox.SelectedItem = selectedItem;
			else
				comboBox.SelectedIndex = -1;
		}

		public void SetRequestTypeComboBox ( )
		{
			if (transaction != null)
			{
				fuelRequestRequestTypeComboBox.Enabled = false;
				if (transaction.Alias == fuelRequestTransactionAlias)
					fuelRequestRequestTypeComboBox.SelectedItem = "Refuel";

				else if (transaction.Alias == defuelRequestTransactionAlias)
					fuelRequestRequestTypeComboBox.SelectedItem = "Defuel";

				else if (transaction.Alias == fillStandTransactionAlias)
				{
					fillStandRequestTypeComboBox.Items.Remove ( "Return To Bulk" );
					if (( transaction.LineItems[0] as LineItemDO ).PartialFill == null
					|| !( transaction.LineItems[0] as LineItemDO ).PartialFill.Value)
						fillStandRequestTypeComboBox.SelectedItem = "Fill";
					else
						fillStandRequestTypeComboBox.SelectedItem = "Partial Fill";
				}

				else if (transaction.Alias == returnToBulkTransactionAlias)
				{
					fillStandRequestTypeComboBox.Items.Remove ( "Fill" );
					fillStandRequestTypeComboBox.Items.Remove ( "Partial Fill" );
					fillStandRequestTypeComboBox.SelectedItem = "Return To Bulk";
					fillStandRequestTypeComboBox.Enabled = false;
				}

				else
					throw new Exception ( "Unrecognized Transaction Alias - " + transaction.Alias );
			}
			else
			{
				if (fuelingServiceRequestTabControl.TabPages.Contains ( fillStandTabPage ))
					fillStandRequestTypeComboBox.SelectedItem = "Fill";
				else
					fuelRequestRequestTypeComboBox.SelectedItem = "Refuel";
			}

			// MOD specific functionality (IGO 2010-Sep-10)
			if (TargetCustomer.MOD == base.GetTargetCustomer ( ))
			{
				UpdateControlsBasedOnTransAlias ( );
			}
			ConfigureAdditionalDataFields ( );
		}

		private void GetTransactionAlias ( )
		{
			FMChannelFactory<ITransactionAliases> transAliasesClient = new FMChannelFactory<ITransactionAliases> ( );
			ITransactionAliases transactionAliases = transAliasesClient.CreateProxy ( );

			if (transaction != null)
			{
				transactionAlias = transactionAliases.Get(Security, transaction.TransactionAliasGuid, true );
			}
			else
			{
				string aliasID = null;

				switch (requestType)
				{
					case REQUEST_TYPE.RequestFuel:
					case REQUEST_TYPE.Transient:
					case REQUEST_TYPE.FastLog:
						{
							if (fuelRequestRequestTypeComboBox.SelectedItem as string == "Refuel")
								aliasID = fuelRequestTransactionAlias;
							else
								aliasID = defuelRequestTransactionAlias;
							break;

						}

					case REQUEST_TYPE.FillStand:
					case REQUEST_TYPE.FastLogFillStand:
						{
							if (fillStandRequestTypeComboBox.SelectedItem as string == "Return To Bulk")
								aliasID = returnToBulkTransactionAlias;
							else
								aliasID = fillStandTransactionAlias;
							break;
						}

					default:
						break;
				}

				if (aliasID == null)
					throw new Exception ( "Invalid Transaciton Alias" );

				Guid aliasGuid = transactionAliases.GetIdentityGuid ( security, aliasID );
				transactionAlias = transactionAliases.Get ( security, aliasGuid, true );
			}

			if (transactionAlias.MultipleLineItems)
