		private void AutoCreateEquipmentReferenceData ( )
		{
			EquipmentDO[] equipmentDOArray = { transaction.DestinationEQ1, transaction.SourceEQ1 };

			FMChannelFactory<IEquipmentTypes> equipTypesClient = new FMChannelFactory<IEquipmentTypes> ( );
			IEquipmentTypes equipmentTypes = equipTypesClient.CreateProxy ( );

			List<EquipmentTypeClass> equipmentTypeCollection = equipmentTypes.Enumerate ( security, null, null );

			FMChannelFactory<IEquipments> equipClient = new FMChannelFactory<IEquipments> ( );
			IEquipments equipments = equipClient.CreateProxy ( );

			string fuelRequestAlias = ConfigurationManager.AppSettings["FuelRequestTransactionAlias"];
			string defuelRequestAlias = ConfigurationManager.AppSettings["DefuelRequestTransactionAlias"];
			string fillstandRequestAlias = ConfigurationManager.AppSettings["FillStandTransactionAlias"];
			string returntobulkRequestAlias = ConfigurationManager.AppSettings["ReturnToBulkTransactionAlias"];

			foreach (EquipmentDO equipmentDO in equipmentDOArray)
			{
				if (equipmentDO == transaction.DestinationEQ1
				&& ConfigurationManager.AppSettings["AutoCreateDestinationEquipmentData"] != "true")
					continue;

				if (equipmentDO == transaction.SourceEQ1
				&& ConfigurationManager.AppSettings["AutoCreateSourceEquipmentData"] != "true")
					continue;

				if (equipmentDO.RegistrationID == null
				|| equipmentDO.RegistrationID == ""
				|| equipmentDO.EquipmentGuid != Guid.Empty)
					continue;

				EQUIPMENT_TYPE attribute = EQUIPMENT_TYPE.OTHER_TYPE;

				if (transactionAlias.ID == fuelRequestAlias ||
					transactionAlias.ID == fillstandRequestAlias)
				{
					if (equipmentDO == transaction.DestinationEQ1)
						attribute = EQUIPMENT_TYPE.AIRCRAFT_TYPE;
					else
						attribute = EQUIPMENT_TYPE.TANKER_TYPE;
				}

				else if (transactionAlias.ID == defuelRequestAlias ||
							transactionAlias.ID == returntobulkRequestAlias)
				{
					if (equipmentDO == transaction.DestinationEQ1)
						attribute = EQUIPMENT_TYPE.TANKER_TYPE;
					else
						attribute = EQUIPMENT_TYPE.AIRCRAFT_TYPE;
				}

				// Cannot create equipment if type cannot be determined
				EQUIPMENT_TYPE[] equipmentAttribute = transactionAlias.GetEquipmentTypes ( ( equipmentDO == transaction.DestinationEQ1 ) ? true : false, 1 );
				if (equipmentAttribute.Length == 0)
					continue;

				EquipmentTypeClass theEquipmentType = null;

				foreach (EquipmentTypeClass equipmentType in equipmentTypeCollection)
				{
					if (equipmentType.Attribute != attribute)
						continue;

					if (!string.IsNullOrEmpty ( equipmentDO.EquipmentModel )
					&& equipmentDO.EquipmentModel != equipmentType.Model)
						continue;

					theEquipmentType = equipmentType;
					break;
				}

				if (theEquipmentType == null)
				{
					foreach (EquipmentTypeClass equipmentType in equipmentTypeCollection)
					{
						if (equipmentType.Attribute != attribute)
							continue;

						theEquipmentType = equipmentType;
						break;
					}
				}

				if (theEquipmentType == null)
				{
					MessageBox.Show ( "Error: Could not set the Equipment Type" );
				}
				else
				{
					EquipmentClass equipment = new EquipmentClass(theEquipmentType);

					equipment.ID = equipmentDO.RegistrationID;
					equipment.Model = equipmentDO.EquipmentModel;
					if (equipmentDO == transaction.DestinationEQ1)
					{
						if (!string.IsNullOrEmpty ( fuelRequestRefCodeComboBox.Text ))
							equipment.Xref = fuelRequestRefCodeComboBox.Text;
						else
							equipment.Xref = equipment.ID.Substring ( equipment.ID.Length - 4 );

						if (transaction.FuelCardGuid != Guid.Empty)
						{
							equipment.FuelCardID = transaction.FuelCardID;
							equipment.FuelCardGuid = transaction.FuelCardGuid;
						}
					}

					equipmentDO.EquipmentGuid = equipments.Add ( security, equipment );

					EquipmentDO lineItemEquipmentDO = ( equipmentDO == transaction.DestinationEQ1 ) ? ( transaction.LineItems[0] as LineItemDO ).DestinationEQ : ( transaction.LineItems[0] as LineItemDO ).SourceEQ;
					lineItemEquipmentDO.EquipmentGuid = equipmentDO.EquipmentGuid;
				}
			}
		}



