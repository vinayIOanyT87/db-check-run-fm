			set
			{
				TransactionSR transactionSR = new TransactionSR ( );
				transactionSR.Security = security;
				transactionSR.TransID = value;
				transactionSR.ConvertUnits = true;

				FMChannelFactory<ITransactionProcessor> transProcessorClient = new FMChannelFactory<ITransactionProcessor> ( );
				ITransactionProcessor transProcessor = transProcessorClient.CreateProxy ( );

				transaction = transProcessor.Process ( transactionSR );

				if (transaction.Number02 == null)
				{
					if (transactionAlias.ID == returnToBulkTransactionAlias
					|| transactionAlias.ID == fillStandTransactionAlias)
						transaction.Number02 = System.Convert.ToDouble ( REQUEST_TYPE.FastLogFillStand );
					else
						transaction.Number02 = System.Convert.ToDouble ( REQUEST_TYPE.FastLog );
				}

				RequestType = (REQUEST_TYPE) System.Convert.ToInt32 ( transaction.Number02.Value );

				if (transaction.Status == TransactionStatus.Completed)
				{
					CompletionMode = true;
					TransactionInitialyCompleted = true;
				}
				else
					TransactionInitialyCompleted = false;

				transIDTextBox.Text = value;

			}
		}

