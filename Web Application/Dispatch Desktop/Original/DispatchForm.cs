		protected override bool ProcessCmdKey ( ref Message msg, Keys keyData )
		{
			// If the tab key is pressed to leave the EquipmentDataGridView or the EquipmentFindComboBox,
			// we want to automatically change selection in the PersonDataGrid to be the
			// operator assigned to this equipment (if any).
			if (msg.Msg == WM_KEYDOWN
			   && keyData == Keys.Tab)
			{
				if (EquipmentDataGridView.Focused
				   || EquipmentFindComboBox.Focused)
				{
					EquipmentDataGridView_SelectPersonnel ( );
				}
			}

			return base.ProcessCmdKey ( ref msg, keyData );
		}

		/// <summary>
		/// This method will search the PersonDataGrid and select the operator
		/// assigned to the currently selected equipment in the EquipmentDataGridView
		/// if any.
		/// </summary>
		void EquipmentDataGridView_SelectPersonnel ( )
		{
			try
			{
				if (EquipmentDataGridView.SelectedRows.Count > 0)
				{
					EquipmentClass Equipment = (EquipmentClass) EquipmentDataGridView.SelectedRows[0].DataBoundItem;

					lock (PersonDataGridView)
					{
						foreach (DataGridViewRow Row in PersonDataGridView.Rows)
						{
							PersonClass Person = (PersonClass) Row.DataBoundItem;

							if (Person.AssignedEquipmentGuid == Equipment.IdentityGuid)
							{
								SelectPersonnelRow ( Row );
								break;
							}
						}
					}
				}
			}
			catch (Exception except)
			{
				ErrorHandler ( except );
			}
		}

		/// <summary>
		/// This method will select the indicated row in the PersonDataGrid and 
		/// set the PersonFindComboBox text as well.
		/// </summary>
		/// <param name="SelectRow"></param>
		private void SelectPersonnelRow ( DataGridViewRow SelectRow )
		{
			foreach (DataGridViewRow Row in PersonDataGridView.Rows)
			{
				Row.Selected = false;
			}

			SelectRow.Selected = true;

			if (PersonDataGridView.FirstDisplayedScrollingRowIndex > SelectRow.Index
			   || PersonDataGridView.FirstDisplayedScrollingRowIndex + PersonDataGridView.DisplayedRowCount ( false ) <= SelectRow.Index)
			{
				PersonDataGridView.FirstDisplayedScrollingRowIndex = SelectRow.Index;
			}


		}

