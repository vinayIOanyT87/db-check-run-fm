				// Equipment must be of a type authorized for the Fillstand alias
				if (CheckEquipmentType ( transactionAlias, Equipment ) == false)
				{
					MessageBox.Show ( this, "Servicing unit is not authorized for Fillstand transaction.  Cannot create fillstand.", "Dispatch", MessageBoxButtons.OK );
					return;
				}

				// Create a fillstand transaction
				FMChannelFactory<ISites> sitesClient = new FMChannelFactory<ISites> ( );
				ISites sites = sitesClient.CreateProxy ( );

				SiteClass site = sites.Get(Security, Security.SiteGuid, false, false, false);
				SiteTimeConverter timeConverter = new SiteTimeConverter ( site );

				TransactionDO Transaction = new TransactionDO ( );
				Transaction.TransactionDateTime = timeConverter.Now ( );
				Transaction.LineItems.Add ( new LineItemDO ( ) );
				Transaction.TransID = FuelsManagerId.NewId ( );
				Transaction.Site = Security.SiteID;
				Transaction.SiteGuid = Security.SiteGuid;
				Transaction.Alias = transactionAlias.ID;
				Transaction.TransTypeID = transactionAlias.TransTypeID;
				Transaction.TransactionAliasGuid = transactionAlias.IdentityGuid;
				Transaction.DocumentNumber = sites.GetNextDocumentNumber(Security, DOCUMENT_TYPE.MANUAL_BOL, Security.SiteGuid);

				FMChannelFactory<IInventoryDateProcessor> inventoryDateProcessorClient = new FMChannelFactory<IInventoryDateProcessor> ( );
				IInventoryDateProcessor inventoryClient = inventoryDateProcessorClient.CreateProxy ( );

				InventoryDateSR inventoryDateSR = new InventoryDateSR ( );
				inventoryDateSR.Security = Security;
				inventoryDateSR.CurrentSiteGuid = Security.SiteGuid;
				InventoryDateDO inventoryDateDO = inventoryClient.Process ( inventoryDateSR );

				Transaction.InventoryDate = inventoryDateDO.InventoryDate;
				Transaction.TransactionDateTime = timeConverter.Now ( );
				Transaction.OriginApplication = TransactionOrigin.Dispatch;
				Transaction.Status = TransactionStatus.Requested;
				Transaction.RequestedDateTime = timeConverter.Now ( );


				FMBusinessObjects.UtilityObjects.UnitsHelperClass unitsHelper = new FMBusinessObjects.UtilityObjects.UnitsHelperClass ( Security, site, transactionAlias, null );
				unitsHelper.SetUnits ( Transaction, 0 );

				FMChannelFactory<ICompanies> companiesClient = new FMChannelFactory<ICompanies> ( );
				ICompanies companies = companiesClient.CreateProxy ( );

				List<CompanyClass> managerCollection = companies.EnumerateByRole ( Security, COMPANY_ROLE.MANAGER, false, true );

				if (managerCollection.Count == 0)
				{
					throw new Exception ( "No Manager" );
				}

				if (managerCollection.Count > 1)
				{
					throw new Exception ( "Multiple Managers" );
				}

				Transaction.ManagerID = managerCollection[0].ID;
				Transaction.ManagerCode = managerCollection[0].Code;
				Transaction.ManagerCompanyGuid = managerCollection[0].IdentityGuid;

				List<CompanyClass> ownerCollection = companies.EnumerateByRole ( Security, COMPANY_ROLE.OWNER, false, true );
				if (ownerCollection.Count == 0)
				{
					throw new Exception ( "No Owner" );
				}

				if (ownerCollection.Count > 1)
				{
					throw new Exception ( "Multiple Owners" );
				}

				Transaction.OwnerID = ownerCollection[0].ID;
				Transaction.OwnerCode = ownerCollection[0].Code;
				Transaction.OwnerCompanyGuid = ownerCollection[0].IdentityGuid;
				Transaction.Number02 = System.Convert.ToDouble ( FuelRequestForm.REQUEST_TYPE.FillStand );

				Transaction.Notes = "";

				ProductClass product = null;

				if (Equipment.ProductGuid != Guid.Empty)
				{
					FMChannelFactory<IProducts> productsClient = new FMChannelFactory<IProducts> ( );
					IProducts products = productsClient.CreateProxy ( );

					product = products.GetByInfoAuthorizedCompanies ( Security, Equipment.ProductGuid, true, false );
					( Transaction.LineItems[0] as LineItemDO ).Product = product.ID;
					( Transaction.LineItems[0] as LineItemDO ).ProductCode = ProductClass.ProductTypeID ( product.ProductType );
					( Transaction.LineItems[0] as LineItemDO ).ProductGuid = product.IdentityGuid;
					unitsHelper.Product = product;
				}
				else
					throw new Exception ( "Selected equipment has no product assignment" );

				unitsHelper.SetUnits ( Transaction.LineItems[0] as LineItemDO, (PRODUCT_TYPE) 0, product );

				( Transaction.LineItems[0] as LineItemDO ).Quantity = new QuantityDO ( 0, 0, 0, 0 );

				// Registration ID
				EquipmentDO equipmentDO = new EquipmentDO ( Equipment );
				Transaction.DestinationEQ1 = equipmentDO;
				Transaction.DestinationEQ1.RegistrationID = Equipment.ID;
				( Transaction.LineItems[0] as LineItemDO ).DestinationEQ = new EquipmentDO ( Equipment );
				( Transaction.LineItems[0] as LineItemDO ).PartialFill = false;

				// Dispatch the transaction
				DispatchTransaction ( Person, Equipment, Transaction );

				AddTransactionToRequestGrid ( Transaction );

			}
			catch (Exception except)
			{
				ErrorHandler ( except );
			}

		}

