		private void DispatchButton_Click ( object sender, EventArgs e )
		{
			try
			{
				// If no selections, stop
				if (EquipmentDataGridView.SelectedRows.Count == 0
				   || PersonDataGridView.SelectedRows.Count == 0
				   || RequestDataGridView.SelectedRows.Count == 0)
				{
					return;
				}

				EquipmentClass equipment = (EquipmentClass) EquipmentDataGridView.SelectedRows[0].DataBoundItem;
				PersonClass person = (PersonClass) PersonDataGridView.SelectedRows[0].DataBoundItem;

				if (CheckEquipmentAndOperator ( equipment, person ) == false)
				{
					return;
				}

				List<TransactionDO> transactions = new List<TransactionDO> ( );

				// Get all the transactions
				lock (RequestDataGridView)
				{
					foreach (DataGridViewRow row in RequestDataGridView.SelectedRows)
					{
						DataRowView dataRow = (DataRowView) row.DataBoundItem;

						string transID = (string) dataRow["TransID"];
						TransactionDO transaction = GetTransaction ( transID );

						transactions.Add ( transaction );

					}
				}

				foreach (TransactionDO trans in transactions)
				{
					TransactionCheckResult result = CheckAdditiveFlag ( trans, equipment );

					if (result == TransactionCheckResult.Cancel)
					{
						return;
					}

					if (result == TransactionCheckResult.Exempted)
					{
						break;
					}

				}

				foreach (TransactionDO trans in transactions)
				{
					TransactionCheckResult result = CheckDefuelStatus ( trans, equipment );

					if (result == TransactionCheckResult.Cancel)
					{
						return;
					}

					if (result == TransactionCheckResult.Exempted)
					{
						break;
					}

				}

				foreach (TransactionDO trans in transactions)
				{
					TransactionCheckResult result = CheckRefuelStatus ( trans, equipment );

					if (result == TransactionCheckResult.Cancel)
					{
						return;
					}

					if (result == TransactionCheckResult.Exempted)
					{
						break;
					}

				}

				foreach (TransactionDO trans in transactions)
				{
					TransactionCheckResult result = CheckGrade ( trans, equipment );

					if (result == TransactionCheckResult.Cancel)
					{
						return;
					}

					if (result == TransactionCheckResult.Exempted)
					{
						break;
					}

				}

				// Dispatch the transactions
				foreach (TransactionDO trans in transactions)
				{
					PerformDispatchTransaction ( person, equipment, trans );
				}

			}

			catch (Exception except)
			{
				ErrorHandler ( except );
			}

		}

		private bool CheckEquipmentAndOperator ( EquipmentClass equipment, PersonClass person )
		{
			if (equipment.LockedOut)
			{
				MessageBox.Show ( this, "Servicing unit is locked-out.  Cannot dispatch this vehicle.", "Dispatch", MessageBoxButtons.OK, MessageBoxIcon.Error );
				return false;
			}

			if (person.LockedOut)
			{
				string message = String.Format ( "[{0},{1}] is locked-out.  Cannot dispatch this agent.", person.LastName, person.FirstName );
				MessageBox.Show ( this, message, "Dispatch", MessageBoxButtons.OK, MessageBoxIcon.Error );
				return false;
			}

			if (String.IsNullOrEmpty ( equipment.IssPtNum ))
			{
				MessageBox.Show ( this, "IssPtNum for Vehicle is blank.  Cannot dispatch this vehicle.", "Dispatch", MessageBoxButtons.OK, MessageBoxIcon.Error );
				return false;
			}

			// Don't dispatch equipment if it is already assigned to another operator
			foreach (PersonClass Operator in personCollection)
			{
				if (Operator.IdentityGuid != person.IdentityGuid)
				{
					if (equipment.IdentityGuid == Operator.AssignedEquipmentGuid)
					{
						string message = "Vehicle is already associated with another operator and may not be assigned to this operator.\n" +
						   "Please choose a different vehicle or different operator and try again.";
						MessageBox.Show ( this, message, "Dispatch", MessageBoxButtons.OK, MessageBoxIcon.Error );

						return false;
					}
				}
			}

			// If selected equipment is not in service, give a warning
			if (equipment.InServiceFlag == false)
			{
				DialogResult result = MessageBox.Show ( this,
				   "This servicing unit is out of service.  Dispatch anyway?",
				   "Dispatch",
				   MessageBoxButtons.YesNo,
				   MessageBoxIcon.Warning );

				if (result == DialogResult.No)
				{
					return false;
				}
			}

			// Give warning if operator is OUT
			if (person.Status == PersonClass.STATUS.Out)
			{
				DialogResult result = MessageBox.Show ( this,
				   "The operator is currently OUT.  Dispatch anyway and update status?",
				   "Dispatch",
				   MessageBoxButtons.YesNo,
				   MessageBoxIcon.Warning );

				if (result == DialogResult.No)
				{
					return false;
				}

			}

			if (equipment._QCDate.Value.Date < timeConverter.Today ( ))
			{
				DialogResult result = MessageBox.Show ( this,
				   "Equipment is overdue QC Checkup.  Dispatch Anyway?",
				   "Dispatch",
				   MessageBoxButtons.YesNo,
				   MessageBoxIcon.Warning );

				if (result == DialogResult.No)
				{
					return false;
				}
			}

			if (person.AssignedEquipmentGuid.IsNotEmptyAndNotEqualTo(equipment.IdentityGuid))
			{
				string message = String.Format ( "{0},{1} is currently assigned to vehicle {2}.  Reassign {0},{1} to {3}?",
				   person.LastName, person.FirstName, person.AssignedEquipmentID, equipment.ID );

				DialogResult result = MessageBox.Show ( this, message, "Dispatch", MessageBoxButtons.YesNo, MessageBoxIcon.Warning );
				if (result == DialogResult.No)
				{
					SelectEquipment ( BaseDataObject.DUMMY_INDEX /*person.AssignedEquipmentGuid */);
					return false;
				}
			}

			// Have to a full get of the Equipment & Person object so we get all the collections we need to check
			FMChannelFactory<IPersonnel> personnelClient = new FMChannelFactory<IPersonnel> ( );
			IPersonnel personnel = personnelClient.CreateProxy ( );

			person = personnel.Get ( Security, person.IdentityGuid );

			FMChannelFactory<ISites> sitesClient = new FMChannelFactory<ISites> ( );
			ISites sites = sitesClient.CreateProxy ( );

			SiteClass site = sites.Get(Security, Security.SiteGuid, getMemberSites: false, getSchedulesAndProcessVariables: false, bGetAssociatedAliases: false);

			FMChannelFactory<IEquipments> equipmentsClient = new FMChannelFactory<IEquipments> ( );
			IEquipments equipments = equipmentsClient.CreateProxy ( );

			equipment = equipments.GetBySite(Security, equipment.IdentityGuid, site);

			FMChannelFactory<IEquipmentTypes> equipmentTypesClient = new FMChannelFactory<IEquipmentTypes>();
			IEquipmentTypes equipmentTypes = equipmentTypesClient.CreateProxy();

			EquipmentTypeClass equipmentType = equipmentTypes.Get(Security, equipment.EquipmentTypeGuid);

			if (equipmentType.ReqQualificationsCollection.Count > 0)
			{
				foreach (QualificationMapClass Qualification in equipmentType.ReqQualificationsCollection)
				{
					QualificationMapClass qualificationRecord = FindQualificationRecord ( person, Qualification, person.QualificationCollection );

					if (qualificationRecord == null)
					{
						string message = String.Format ( "{0},{1} does not have the '{2}' required qualification.  Dispatch anyway?",
						   person.LastName, person.FirstName, Qualification.ID );

						DialogResult result = MessageBox.Show ( this, message, "Dispatch", MessageBoxButtons.YesNo, MessageBoxIcon.Warning );
						if (result == DialogResult.No)
						{
							return false;
						}
					}
					else if (qualificationRecord.ExpirationDate.Value < timeConverter.Today ( ))
					{
						string message = String.Format ( "{0},{1} has the '{2}' required qualification but it has expired.  Dispatch anyway?",
						   person.LastName, person.FirstName, Qualification.ID );

						DialogResult result = MessageBox.Show ( this, message, "Dispatch", MessageBoxButtons.YesNo, MessageBoxIcon.Warning );
						if (result == DialogResult.No)
						{
							return false;
						}
					}
				}
			}

			if (equipmentType.ReqTrainingCollection.Count > 0)
			{
				foreach (QualificationMapClass Training in equipmentType.ReqTrainingCollection)
				{
					QualificationMapClass trainingRecord = FindQualificationRecord ( person, Training, person.TrainingCollection );

					if (trainingRecord == null)
					{
						string message = String.Format ( "{0},{1} does not have the '{2}' required training.  Dispatch anyway?",
						   person.LastName, person.FirstName, Training.ID );

						DialogResult result = MessageBox.Show ( this, message, "Dispatch", MessageBoxButtons.YesNo, MessageBoxIcon.Warning );
						if (result == DialogResult.No)
						{
							return false;
						}
					}
					else if (trainingRecord.ExpirationDate.Value < timeConverter.Today ( ))
					{
						string message = String.Format ( "{0},{1} has the '{2}' required training but it has expired.  Dispatch anyway?",
						   person.LastName, person.FirstName, Training.ID );

						DialogResult result = MessageBox.Show ( this, message, "Dispatch", MessageBoxButtons.YesNo, MessageBoxIcon.Warning );
						if (result == DialogResult.No)
						{
							return false;
						}
					}
				}
			}

			if (equipment.TagAndLicenseCollection.Count > 0)
			{
				foreach (QualificationMapClass TagLicense in equipment.TagAndLicenseCollection)
				{
					if (TagLicense.ExpirationDate.Value < timeConverter.Today ( ))
					{
						string message = String.Format ( "Tag/License [{0}] for servicing unit has expired.  Dispatch anyway?", TagLicense.ID );

						DialogResult result = MessageBox.Show ( this, message, "Dispatch", MessageBoxButtons.YesNo, MessageBoxIcon.Warning );
						if (result == DialogResult.No)
						{
							return false;
						}
					}
				}
			}

			if (equipment.TestAndInspectionCollection.Count > 0)
			{
				foreach (QualificationMapClass TestInspection in equipment.TestAndInspectionCollection)
				{
					if (TestInspection.ExpirationDate.Value < timeConverter.Today ( ))
					{
						string message = String.Format ( "Test/Inspection [{0}] for servicing unit has expired.  Dispatch anyway?", TestInspection.ID );

						DialogResult result = MessageBox.Show ( this, message, "Dispatch", MessageBoxButtons.YesNo, MessageBoxIcon.Warning );
						if (result == DialogResult.No)
						{
							return false;
						}
					}
				}
			}

			// If the equiment is in service, the last quality tag should not be taken into account here
			FMChannelFactory<IEquipmentQualityTagLogs> equipmentQualityTagLogsClient = new FMChannelFactory<IEquipmentQualityTagLogs> ( );
			IEquipmentQualityTagLogs logs = equipmentQualityTagLogsClient.CreateProxy ( );

			EquipmentQualityTagLogClass tag = logs.GetMostRecentByEquipmentID ( Security, equipment.ID );

			if (tag != null && tag.IdentityGuid != Guid.Empty && string.IsNullOrEmpty ( tag.RemovedBy ))
			{
				if (tag.QualityTagGuid != Guid.Empty)
				{
					FMChannelFactory<IQualityTags> qualityTagsClient = new FMChannelFactory<IQualityTags> ( );
					IQualityTags qualityTags = qualityTagsClient.CreateProxy ( );

					QualityTagClass qualityTag = qualityTags.Get ( Security, tag.QualityTagGuid);

					if (qualityTag.Severity == QUALITY_SEVERITY_LEVELS.CAUTION || qualityTag.Severity == QUALITY_SEVERITY_LEVELS.WARNING)
					{
						string message = String.Format ( "The servicing unit has a {0} tag.  Do you still wish to send this servicing unit?",
						   Enum.GetName ( typeof ( QUALITY_SEVERITY_LEVELS ), equipment.QualityTag.Severity ) );

						DialogResult result = MessageBox.Show ( this, message, "Dispatch", MessageBoxButtons.YesNo, MessageBoxIcon.Warning );
						if (result == DialogResult.No)
						{
							return false;
						}

					}

					if (qualityTag.Severity == QUALITY_SEVERITY_LEVELS.DANGER)
					{
						string message = "The servicing unit has a DANGER tag.  This service unit cannot be dispatched.";
						MessageBox.Show ( this, message, "Dispatch", MessageBoxButtons.OK, MessageBoxIcon.Error );
						return false;
					}
				}

			}

			return true;
		}

