		void RequestDataGridView_SelectionChanged ( object sender, EventArgs e )
		{
			try
			{
				DispatchButton.Enabled = false;
				CancelDispatchButton.Enabled = false;

				if (RequestDataGridView.SelectedRows.Count > 0)
				{
					bool bNewCancelState = Security.HasRight ( RIGHT.MODIFY_DISPATCH );
					bool bNewDispatchState = Security.HasRight ( RIGHT.MODIFY_DISPATCH );

					lock (RequestDataGridView)
					{
						foreach (DataGridViewRow gridRow in RequestDataGridView.SelectedRows)
						{
							DataRowView dataRow = (DataRowView) gridRow.DataBoundItem;

							string statusText = (string) dataRow["TransactionStatus"];
							TransactionStatus status = (TransactionStatus) Enum.Parse ( typeof ( TransactionStatus ), statusText );

							bNewCancelState &= ( status == TransactionStatus.Dispatched )
