				Transaction.SourceEQ1.RegistrationID = Equipment.ID;
				( Transaction.LineItems[0] as LineItemDO ).SourceEQ = new EquipmentDO ( Equipment );

				// Dispatch the transaction
				DispatchTransaction ( Person, Equipment, Transaction );

				AddTransactionToRequestGrid ( Transaction );

			}
			catch (Exception except)
			{
				ErrorHandler ( except );
			}

		}

