		private void UpdateRequestView ( )
		{
			try
			{
				string selectedTransID = string.Empty;
				string CurrentRowTransID = string.Empty;

				ISynchronizeInvoke i = (ISynchronizeInvoke) this;

				// Check if the event was generated from another
				// thread and needs invoke instead
				if (i.InvokeRequired)
				{
					DispatchDataAccess.OnDataUpdatedHandler tempDelegate = new DispatchDataAccess.OnDataUpdatedHandler ( UpdateRequestView );
					i.BeginInvoke ( tempDelegate, null );
					return;
				}
				// store the current selection and currentrow
				// does not allow multiple selections so we just need to store one if selected
				lock (RequestDataGridView)
				{
					if (RequestDataGridView.SelectedRows.Count > 0)
					{
						DataRowView Row = (DataRowView) RequestDataGridView.SelectedRows[0].DataBoundItem;
						selectedTransID = (string) Row["TransID"];
					}

					// store the current row so it can be restored
					if (RequestDataGridView.CurrentRow != null)
					{
						DataRowView CurrentRow = (DataRowView) RequestDataGridView.Rows[RequestDataGridView.CurrentRow.Index].DataBoundItem;
						if (CurrentRow != null)
							CurrentRowTransID = (string) CurrentRow["TransID"];
					}

					RequestDataGridView.AutoGenerateColumns = false;

					DispatchTransactionsDO results = DataAccess.GetTransactions ( sr );
					UpdateGrid ( results );

					if (!string.IsNullOrEmpty ( selectedTransID ) ||
						!string.IsNullOrEmpty ( CurrentRowTransID ))
					{
						// restore the selection
						foreach (DataGridViewRow Row in RequestDataGridView.Rows)
						{
							DataRowView dataRow = (DataRowView) Row.DataBoundItem;
							if (dataRow != null)
							{
								if (!string.IsNullOrEmpty ( selectedTransID ) &&
									selectedTransID.Equals ( (string) dataRow["TransID"] ))
								{
									Row.Selected = true;
								}
								// check for the current row
								if (!string.IsNullOrEmpty ( CurrentRowTransID ) &&
									CurrentRowTransID.Equals ( (string) dataRow["TransID"] ))
								{
									// restore the current selection
									// the only way to do this is by setting the currentcell variable since the currentrow is read only
									RequestDataGridView.CurrentCell = Row.Cells[0];
								}
							}
						}
					}
				}

			}
			catch (Exception except)
			{
				ErrorHandler ( except );
			}
		}

		private void UpdateGrid ( DispatchTransactionsDO results )
		{
			DataView view = new DataView ( results.Transactions.Tables[0] );

			// Filter out Completed and Cancelled
			view.RowFilter = "TransactionStatusInt <> " + ( (int) TransactionStatus.Completed ).ToString ( ) +
									" AND TransactionStatusInt <> " + ( (int) TransactionStatus.Cancelled ).ToString ( ) +
									" AND TransactionStatusInt <> " + ( (int) TransactionStatus.Posted ).ToString ( );

			//			view.RowFilter = "TransactionStatusInt <> 0 AND TransactionStatusInt <> 7";
			RequestDataGridView.DataSource = view;

			int index = 1;
			foreach (DataGridViewRow Row in RequestDataGridView.Rows)
			{
				Row.HeaderCell.Value = index.ToString ( );
				Row.Selected = false;
				++index;
			}

		}

		private void UpdatePersonnelView ( )
		{
			try
			{
				ISynchronizeInvoke i = (ISynchronizeInvoke) this;

				// Check if the event was generated from another
				// thread and needs invoke instead
				if (i.InvokeRequired)
				{
					DispatchDataAccess.OnDataUpdatedHandler tempDelegate = new DispatchDataAccess.OnDataUpdatedHandler ( UpdatePersonnelView );
					i.BeginInvoke ( tempDelegate, null );
					return;
				}

				Guid selectedItemGuid = Guid.Empty;
				lock (PersonDataGridView)
				{
					if (PersonDataGridView.SelectedRows.Count > 0)
					{
						PersonClass SelectedPerson = (PersonClass) PersonDataGridView.SelectedRows[0].DataBoundItem;
						selectedItemGuid = SelectedPerson.IdentityGuid;
					}

					PersonDataGridView.AutoGenerateColumns = false;
					personCollection = DataAccess.GetPersonnel ( Security );

					PersonFilterDropDown_SelectedIndexChanged ( null, null );

					if (personCollection.Count > 0 && PersonDataGridView.SelectedRows.Count == 0 && PersonDataGridView.Rows.Count > 0)
					{
						PersonDataGridView.Rows[0].Selected = true;
					}

					// if the calling routine passed in a person try to locate and then select it as the default
					if (SelectedPersonID != null &&
						SelectedPersonID.Length > 0)
					{
						int SelectedIndex = PersonFindComboBox.FindString ( SelectedPersonID );
						if (SelectedIndex >= 0)
						{
							// selection found so set it and update
							PersonFindComboBox.SelectedIndex = SelectedIndex;
						}
					}
					else if (selectedItemGuid != Guid.Empty)
					{
						foreach (DataGridViewRow Row in PersonDataGridView.Rows)
						{
							PersonClass CheckPerson = (PersonClass) Row.DataBoundItem;
							if (CheckPerson.IdentityGuid == selectedItemGuid)
							{
								SelectPersonnelRow ( Row );
								break;
							}
						}
					}
				}

				if (SelectedEquipmentID != null &&
					SelectedEquipmentID.Length > 0)
				{
					for (int iLoop = 0; iLoop < EquipmentFindComboBox.Items.Count; iLoop++)
					{
						EquipmentClass equipment = (EquipmentClass) EquipmentFindComboBox.Items[iLoop];
						if (equipment.ID == SelectedEquipmentID)
						{
							EquipmentFindComboBox.SelectedItem = equipment;
							break;
						}
					}
				}

			}
			catch (Exception except)
			{
				ErrorHandler ( except );
			}
		}

