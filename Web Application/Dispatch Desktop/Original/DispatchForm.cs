		void EquipmentDataGridView_CellFormatting ( object sender, DataGridViewCellFormattingEventArgs e )
		{
			try
			{
				EquipmentClass Equipment = (EquipmentClass) EquipmentDataGridView.Rows[e.RowIndex].DataBoundItem;

				e.CellStyle.SelectionBackColor = Color.Black;

				if (Equipment.LockedOut
				   || Equipment._QCDate.Value < timeConverter.Today ( ))
				{
					e.CellStyle.ForeColor = Color.Gray;
					e.CellStyle.SelectionForeColor = Color.Gray;
				}
				else
				{
					if (Equipment.InServiceFlag)
					{
						if (Equipment.FuelingType == FUELING_TYPES.REFUELER)
						{
							e.CellStyle.ForeColor = Color.Blue;
							e.CellStyle.SelectionForeColor = Color.Yellow;
						}
						else if (Equipment.FuelingType == FUELING_TYPES.DEFUELER)
						{
							e.CellStyle.ForeColor = Color.Red;
							e.CellStyle.SelectionForeColor = Color.Red;
						}
						else
						{
							e.CellStyle.ForeColor = Color.Black;
							e.CellStyle.SelectionForeColor = Color.White;
						}
					}
					else
					{
						e.CellStyle.ForeColor = Color.Gray;
						e.CellStyle.SelectionForeColor = Color.Gray;
					}
				}

			}
			catch (Exception except)
			{
				ErrorHandler ( except );
			}
		}

