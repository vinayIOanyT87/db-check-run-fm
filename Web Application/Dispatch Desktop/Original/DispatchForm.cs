		private bool CheckTransactionsForDispatch ( EquipmentClass equipment, PersonClass person, TransactionDO transaction )
		{
			if (transaction == null)
			{
				throw new ArgumentException ( "Transaction not found" );
			}

			// Give warning message if dispatching to cross type
			if (CheckDefuelStatus ( transaction, equipment ) == TransactionCheckResult.Cancel)
			{
				return false;
			}

			if (CheckRefuelStatus ( transaction, equipment ) == TransactionCheckResult.Cancel)
			{
				return false;
			}

			if (CheckGrade ( transaction, equipment ) == TransactionCheckResult.Cancel)
			{
				return false;
			}

			if (CheckAdditiveFlag ( transaction, equipment ) == TransactionCheckResult.Cancel)
			{
				return false;
			}

			return true;

		}

		private bool DispatchTransaction ( PersonClass person, EquipmentClass equipment, TransactionDO transaction )
		{
			if (CheckEquipmentAndOperator ( equipment, person ))
			{
				if (CheckTransactionsForDispatch ( equipment, person, transaction ))
				{
					PerformDispatchTransaction ( person, equipment, transaction );
					return true;
				}
			}

			return false;
		}

		private void PerformDispatchTransaction ( PersonClass person, EquipmentClass equipment, TransactionDO transaction )
		{
			// Dispatch
			transaction.OperatorPersonnelGuid = person.IdentityGuid;
			transaction.OperatorID = person.ID;

			LineItemDO LineItem = (LineItemDO) transaction.LineItems[0];

			switch (transaction.TransTypeID)
			{
				case TransactionTypes.T4_SecondaryDefuel:
				case TransactionTypes.T7_FillStand:
					transaction.DestinationEQ1 = new EquipmentDO ( equipment );
					transaction.DestinationEQ1.RegistrationID = equipment.ID;
					LineItem.DestinationEQ = new EquipmentDO ( equipment );
					LineItem.DestinationEQ.RegistrationID = equipment.ID;
					break;

				case TransactionTypes.T6_SecondaryDisbursement:
				case TransactionTypes.T10_Unload:
				case TransactionTypes.T12_InventoryNotAffected:
					transaction.SourceEQ1 = new EquipmentDO ( equipment );
					transaction.SourceEQ1.RegistrationID = equipment.ID;
					LineItem.SourceEQ = new EquipmentDO ( equipment );
					LineItem.SourceEQ.RegistrationID = equipment.ID;
					break;

				default:
					throw new ApplicationException ( "Unhandled transaction type passed to dispatch." );

			}

			transaction.Status = TransactionStatus.Dispatched;
			foreach (LineItemDO lineitem in transaction.LineItems)
			{
				lineitem.Status = TransactionStatus.Dispatched;

				foreach (SubLineItemDO sublineitem in lineitem.SubLineItems)
				{
					sublineitem.Status = TransactionStatus.Dispatched;
				}
			}

			person.AssignedEquipmentID = equipment.ID;
			person.AssignedEquipmentGuid = equipment.IdentityGuid;
			person.Status = PersonClass.STATUS.In;

			transaction.DispatchedDateTime = timeConverter.Now ( );

			// Set IssPt and IssPtNum
			transaction.IssuePoint = equipment.IssPt;
			transaction.IssuePointNumber = equipment.IssPtNum;

			SaveTransaction ( transaction, person );

		}

