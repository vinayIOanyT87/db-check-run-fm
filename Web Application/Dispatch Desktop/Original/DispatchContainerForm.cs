		/// <summary>
		/// This method is responsible for updating the grid's datasource
		/// </summary>
		private void UpdateViewWithNotification ( )
		{
			ISynchronizeInvoke i = (ISynchronizeInvoke) this;

			// Check if the event was generated from another
			// thread and needs invoke instead
			if (i.InvokeRequired)
			{
				DispatchDataAccess.OnDataUpdatedHandler tempDelegate = new DispatchDataAccess.OnDataUpdatedHandler ( UpdateViewWithNotification );
				i.BeginInvoke ( tempDelegate, null );
				return;
			}

			UpdateView ( );

		}

		private void UpdateView ( )
		{
			// store the currently selected rows so we can reset them after an update
			string[] selectedTransID = new string[dataGridView1.SelectedRows.Count];
			int NumberOfSelectedRows = dataGridView1.SelectedRows.Count;
			string CurrentRowTransID = string.Empty;

			for (int iLoop = 0; iLoop < NumberOfSelectedRows; iLoop++)
			{
				DataRowView Row = (DataRowView) dataGridView1.SelectedRows[iLoop].DataBoundItem;
				selectedTransID[iLoop] = (string) Row["TransID"];
			}

			// store the current row so it can be restored
			if (dataGridView1.CurrentRow != null)
			{
				DataRowView CurrentRow = (DataRowView) dataGridView1.Rows[dataGridView1.CurrentRow.Index].DataBoundItem;
				if (CurrentRow != null)
					CurrentRowTransID = (string) CurrentRow["TransID"];
			}


			if (dispatchSR != null)
			{
				dispatchSR.Security = Security;
				dispatchSR.BeginDate = BeginDatePicker.Value;
				dispatchSR.EndDate = EndDatePicker.Value;

				GetStatusValues ( dispatchSR );
				GetAliases ( dispatchSR );

				DispatchTransactionsDO results = null;

				DataAccess.ClearOnChange ( );
				DataAccess = new DispatchDataAccess (Security);
				DataAccess.OnDataUpdated += new DispatchDataAccess.OnDataUpdatedHandler ( UpdateViewWithNotification );
				DataAccess.OnError += new DispatchDataAccess.OnErrorHandler ( ErrorHandler );

				results = DataAccess.GetTransactions ( dispatchSR );

				lock (dataGridView1)
				{
					dataGridView1.AutoGenerateColumns = false;

					DataView view = new DataView ( results.Transactions.Tables[0] );

					dataGridView1.DataSource = view;

					LoadVehicleDropDown ( results.Transactions.Tables[0] );

					// since the grid will autoselect the first row we need to reset the selection before we then set it
					// Set the row number display text values
					int index = 1;
					foreach (DataGridViewRow Row in dataGridView1.Rows)
					{
						DataRowView dataRow = (DataRowView) Row.DataBoundItem;
						Row.HeaderCell.Value = index.ToString ( );
						if (NumberOfSelectedRows > 0)
							Row.Selected = false;
						if (!string.IsNullOrEmpty ( CurrentRowTransID ) &&
						 CurrentRowTransID.Equals ( (string) dataRow["TransID"] ))
						{
							// restore the current selection
							// the only way to do this is by setting the currentcell variable since the currentrow is read only
							dataGridView1.CurrentCell = Row.Cells[0];
						}
						++index;
					}
					// we only do this if there are selections already made
					if (NumberOfSelectedRows > 0)
					{
						// restore the selected rows if they are still visible
						for (int iLoop = 0; iLoop < NumberOfSelectedRows; iLoop++)
						{
							foreach (DataGridViewRow Row in dataGridView1.Rows)
							{
								DataRowView dataRow = (DataRowView) Row.DataBoundItem;
								if (dataRow != null)
								{
									if (selectedTransID[iLoop].Equals ( (string) dataRow["TransID"] ))
									{
										Row.Selected = true;

										if (dataGridView1.FirstDisplayedScrollingRowIndex + dataGridView1.DisplayedRowCount ( false ) <= Row.Index)
										{
											dataGridView1.FirstDisplayedScrollingRowIndex =
											 Row.Index - dataGridView1.DisplayedRowCount ( false ) + 1;
										}
										break;
									}
								}
							}
						}
					}
				}
			}
		}

		/// <summary>
		/// This method loads the Vehicle combobox with unique, non-empty vehicle XREF values
		/// from the data items in the main grid data source.  Selection is preserved
		/// if appropriate.
		/// </summary>
		/// <param name="dataTable"></param>
		private void LoadVehicleDropDown ( DataTable dataTable )
		{
			// Set the vehicle combo box to the same - use a new view so they
			// are separate.

			// Save the current selection
			string selecteVehicleXref = vehicleComboBox.Text;

			// Clear the items from the combobox and add the ALL option
			vehicleComboBox.Items.Clear ( );
			vehicleComboBox.Items.Add ( "{All}" );

			// Get a list of vehicle XREFs that are not empty
			var vehicleIDs = from V in dataTable.AsEnumerable ( )
							 where string.IsNullOrEmpty ( V["XREF"].ToString ( ) ) == false
							 select V["XREF"] as string;

			// Load the combo box with unique values
			foreach (var V in vehicleIDs)
			{
				if (vehicleComboBox.FindStringExact ( V ) == -1)
				{
					vehicleComboBox.Items.Add ( V );
				}
			}

			// Set the selection back to what it was if the item exists in the
			// combo any more.
			if (vehicleComboBox.FindStringExact ( selecteVehicleXref ) > 0)
			{
				vehicleComboBox.Text = selecteVehicleXref;
			}
			else
			{
				vehicleComboBox.SelectedIndex = 0;
			}

		}

