		void dataGridView1_CellFormatting ( object sender, DataGridViewCellFormattingEventArgs e )
		{
			// Transactions need to be displayed in different colors by requirement
			// Red = open defuel
			// Gray = canceled or Complete requests
			// Blue = open refuel
			// Black = other dispatch transactions

			// Find the data record
			DataRowView row = (DataRowView) dataGridView1.Rows[e.RowIndex].DataBoundItem;

			// Set the appropriate color
			string aliasName = (string) row["AliasName"];
			TransactionStatus status = (TransactionStatus) Enum.Parse ( typeof ( TransactionStatus ), (string) row["TransactionStatus"] );
			bool transactionStatusOpen = TransactionStatusOpen ( status );

			e.CellStyle.SelectionBackColor = Color.Black;

			if (aliasName.Equals ( "Defuel" ) && transactionStatusOpen)
			{
				e.CellStyle.ForeColor = Color.Red;
				e.CellStyle.SelectionForeColor = Color.Cyan;
			}
			else if (aliasName.Equals ( "Refuel" ) && transactionStatusOpen)
			{
				e.CellStyle.ForeColor = Color.Blue;
				e.CellStyle.SelectionForeColor = Color.Yellow;
			}
			else if (transactionStatusOpen == false)
			{
				e.CellStyle.ForeColor = Color.Gray;
				e.CellStyle.SelectionForeColor = Color.Gray;
			}
			else
			{
				e.CellStyle.ForeColor = Color.Black;
				e.CellStyle.SelectionForeColor = Color.White;
			}

		}

		public static bool TransactionStatusOpen ( TransactionStatus status )
		{
			bool bClosed = status == TransactionStatus.Cancelled
			|| status == TransactionStatus.Closed
			|| status == TransactionStatus.Completed
			|| status == TransactionStatus.Posted
			|| status == TransactionStatus.OnHold;

			return !bClosed;

		}

