					PopupContextMenuForDataGrid.Items[4].Enabled = false; //Set Fillstand Completed
			}
			else if (System.Convert.ToBoolean ( useArrivalTime ) == false &&
			 System.Convert.ToBoolean ( useStartTime ) == true &&
			 System.Convert.ToBoolean ( useStopTime ) == false)
			{
				PopupContextMenuForDataGrid.Items[0].Enabled = false;	// set arrived
				PopupContextMenuForDataGrid.Items[1].Enabled = !( anyRequested || anyStarted || anyStopped || anyCompletedCanceled || anyRecirculation );	// set arrived;	//Set Service Started
