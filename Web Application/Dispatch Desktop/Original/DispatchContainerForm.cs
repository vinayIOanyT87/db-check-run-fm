		/// <summary>
		/// This function enables and disables the appropriate state transitions on
		/// the Dispatch grid popup menu and the Operation menu on the menu bar
		/// 
		/// The states of a transaction in Dispatch are:
		/// <list type="bullet">
		/// <item><term>In-process states</term><descriptions>Active transactions; i.e., not completed or cancelled</descriptions></item>
		/// <list type="bullet">
		/// <item><term>Requested</term></item>
		/// <item><term>Dispatched</term></item>
		/// <item><term>Arrived</term></item>
		/// <item><term>Started</term></item>
		/// <item><term>Stopped</term></item>
		/// </list>
		/// <item><term>Completed</term></item>
		/// <item><term>Cancelled</term></item>
		/// </list>
		/// 
		/// Possible state transitions are determined by the current state and the Optional Times configuration
		/// </summary>
		/// <remarks>
		/// Logic changed 3.7.2010 by CHK to allow a transition away from a state not currently required by the Optional Times configuration
		/// See bug 12158
		/// 
		/// Logic change is that now the assumption starts that a transition is valid.  We then look for disqualifiers
		/// <list>
		/// <listheader><term>Disqualifiers for in-process transitions</term></listheader>
		/// <item><term>Any selected transaction is already in an end state:  id est, Completed or Cancelled</term></item>
		/// <item><term>Any selected transaction is already at or past the state moved to by the tested transition</term></item>
		/// <item><term>Any selected transaction would skip a standard or configured state to make the tested transition</term></item>
		/// <item><term>Any selected transaction is a recirculation</term></item>
		/// </list>
		/// <list>
		/// <listheader><term>Disqualifiers for Completion transition</term></listheader>
		/// <item><term>Any selected transaction is already in an end state:  id est, Completed or Cancelled</term></item>
		/// <item><term>Any selected transaction would skip a standard or configured state to make the tested transition</term></item>
		/// <item><term>Any selected transaction is a recirculation</term></item>
		/// </list>
		/// <list>
		/// <listheader><term>Disqualifiers for Cancellation transitions</term></listheader>
		/// <item><term>Any selected transaction is already in an end state:  id est, Completed or Cancelled</term></item>
		/// <item><term>Any selected transaction is a recirculation</term></item>
		/// </list>
		/// 
		/// Note that the check for recirculations really is redundant; recirculations are created as completed.
		/// This check will be left in for now, as recirculations could change in the future.
		/// </remarks>
		private void SetPopupMenuEnableDisable ( )
		{
			bool anyDispatched = false;
			bool anyStarted = false;
			bool anyStopped = false;
			bool anyArrived = false;
			bool allCompleteCapable = true;
			bool allFillstandCapable = true;
			bool refuelDefuelSelected = true;
			bool allCancelCapable = true;
			bool anyRecirculation = false;
			bool anyRequested = false;
			bool anyCompletedCanceled = false;
			bool anyPostedSelected = false;

			string useArrivalTime = ConfigurationManager.AppSettings["Use Arrival Time"];
			string useStartTime = ConfigurationManager.AppSettings["Use Start Time"];
			string useStopTime = ConfigurationManager.AppSettings["Use Stop Time"];

			// items selected so deal with those
			lock (dataGridView1)
			{
				if (dataGridView1.SelectedRows.Count > 0)
				{
					foreach (DataGridViewRow SelectedRow in dataGridView1.SelectedRows)
					{
						DataRowView Row = (DataRowView) SelectedRow.DataBoundItem;
						TransactionStatus status = (TransactionStatus) Enum.Parse ( typeof ( TransactionStatus ), (string) Row["TransactionStatus"] );
						string aliasName = (string) Row["AliasName"];
						if (aliasName.Equals ( "Recirculation" ))
						{
							allCompleteCapable = false;
							allFillstandCapable = false;

							if (status == TransactionStatus.Cancelled ||
								 status == TransactionStatus.Completed)
							{
								allCancelCapable = false;
								anyCompletedCanceled = true;
							}

							anyRecirculation = true;
						}
						else
						{
							if (status == TransactionStatus.Requested)
							{
								anyRequested = true;
							}

							if (status == TransactionStatus.Dispatched)
							{
								anyDispatched = true;
							}

							if (status == TransactionStatus.Arrived)
							{
								anyArrived = true;
							}

							if (status == TransactionStatus.Started)
							{
								anyStarted = true;
							}

							if (status == TransactionStatus.Stopped)
							{
								anyStopped = true;
							}

							if (status == TransactionStatus.Posted)
							{
								anyPostedSelected = true;
							}

							if (aliasName.Equals ( "Fillstand" ) ||
								aliasName.Equals ( "Return to Bulk" ))
								allCompleteCapable = false;
							else
								allFillstandCapable = false;

							if (status == TransactionStatus.Cancelled ||
								 status == TransactionStatus.Completed)
							{
								allCancelCapable = false;
								allCompleteCapable = false;
								allFillstandCapable = false;
								anyCompletedCanceled = true;
							}
						}

						short TransTypeID = (short) Row["TransTypeID"];
						if (TransTypeID != 4 && TransTypeID != 6)
						{
							refuelDefuelSelected = true;
						}
					}
				}
				else
				{
					allCompleteCapable = false;
					allFillstandCapable = false;
					refuelDefuelSelected = false;
					allCancelCapable = false;
				}
			}

			if (PopupContextMenuForDataGrid == null || PopupContextMenuForDataGrid.Items.Count == 0)
			{
				return;
			}

			// if any transaction with status of posted is selected disable everything
			if (anyPostedSelected == true)
			{
				PopupContextMenuForDataGrid.Items[0].Enabled = false;
				PopupContextMenuForDataGrid.Items[1].Enabled = false;
				PopupContextMenuForDataGrid.Items[2].Enabled = false;
				PopupContextMenuForDataGrid.Items[3].Enabled = false;
				PopupContextMenuForDataGrid.Items[4].Enabled = false;
				PopupContextMenuForDataGrid.Items[6].Enabled = false;
				PopupContextMenuForDataGrid.Items[7].Enabled = false;
				arrivalToolStripMenuItem.Enabled = PopupContextMenuForDataGrid.Items[0].Enabled;
				startOfServiceToolStripMenuItem.Enabled = PopupContextMenuForDataGrid.Items[1].Enabled;
				stopOfServiceToolStripMenuItem.Enabled = PopupContextMenuForDataGrid.Items[2].Enabled;
				serviceCompletionToolStripMenuItem.Enabled = PopupContextMenuForDataGrid.Items[3].Enabled;
				fillstandCompletionToolStripMenuItem.Enabled = PopupContextMenuForDataGrid.Items[4].Enabled;
				return;
			}

			if (System.Convert.ToBoolean ( useArrivalTime ) == false &&
			 System.Convert.ToBoolean ( useStartTime ) == false &&
			 System.Convert.ToBoolean ( useStopTime ) == false)
			{
				PopupContextMenuForDataGrid.Items[0].Enabled = false;	// set arrived
				PopupContextMenuForDataGrid.Items[1].Enabled = false;	//Set Service Started
				PopupContextMenuForDataGrid.Items[2].Enabled = false;	//Set Service Stopped

				if (!anyRequested && allCompleteCapable)
				{
					// The only in-process status which invalidates the state transition to 
					// Completed is Requested (must still be Dispatched)
					PopupContextMenuForDataGrid.Items[3].Enabled = true;	//Set Service Completed
				}
				else
					PopupContextMenuForDataGrid.Items[3].Enabled = false; //Set Service Completed

				if (!anyRequested && allFillstandCapable)
				{
					// The only in-process status which invalidates the state transition to 
					// Completed is Requested (must still be Dispatched)
					PopupContextMenuForDataGrid.Items[4].Enabled = true;	//Set Service Completed
				}
				else
					PopupContextMenuForDataGrid.Items[4].Enabled = false; //Set Fillstand Completed
			}
			else if (System.Convert.ToBoolean ( useArrivalTime ) == true &&
			 System.Convert.ToBoolean ( useStartTime ) == false &&
			 System.Convert.ToBoolean ( useStopTime ) == false)
			{
