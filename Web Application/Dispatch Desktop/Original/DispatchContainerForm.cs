		private bool SaveTransactionToDataBase ( SecurityClass security, TransactionDO transaction )
		{
			SaveTransactionsSR saveTransactionsSR = new SaveTransactionsSR ( );
			saveTransactionsSR.IndividualDbTransaction = false;
			saveTransactionsSR.Security = security;
			saveTransactionsSR.CurrentSiteGuid = security.SiteGuid;
			saveTransactionsSR.ConvertUnits = true;
			saveTransactionsSR.Transactions.Add ( transaction );

			for (int Retry = 0; Retry < 3; Retry++)
			{
				try
				{
					FMChannelFactory<ISaveTransactionsProcessor> saveTransProcessorClient = new FMChannelFactory<ISaveTransactionsProcessor> ( );
					ISaveTransactionsProcessor service = saveTransProcessorClient.CreateProxy ( );

					service.SaveTransactions ( saveTransactionsSR );
					return true;
				}
				catch (Exception e)
				{
					if (typeof ( SaveTransactionsException ).IsInstanceOfType ( e ))
					{
						SaveTransactionsException saveTransactionsException = (SaveTransactionsException) e;
						if (saveTransactionsException.Results.Count >= 1
							&& typeof ( TransactionValidationResult ).IsInstanceOfType ( saveTransactionsException.Results[0] )
							&& ( (TransactionValidationResult) saveTransactionsException.Results[0] ).ErrorList.Count >= 1)
						{
							MessageBox.Show ( ( (TransactionValidationResult) saveTransactionsException.Results[0] ).ErrorList[0], "Error" );
						}
						else
						{
							MessageBox.Show ( "Unknown SaveTransactionException", "Error" );
						}
					}

					if (Retry < 2)
					{
						continue;
					}

					break;
				}
			}
			return false;
		}

