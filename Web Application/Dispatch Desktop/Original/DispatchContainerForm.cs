		private void Relog ( object sender, EventArgs e )
		{
			try
			{
				if (Security.HasRight ( RIGHT.MODIFY_DISPATCH ) == false)
				{
					return;
				}

				// Don't allow relog of FillStand
				foreach (DataGridViewRow SelectedRow in dataGridView1.SelectedRows)
				{
					DataRowView Row = (DataRowView) SelectedRow.DataBoundItem;
					TransactionTypes type = (TransactionTypes) Row["TransTypeID"];
					if (type == TransactionTypes.T7_FillStand)
					{
						throw new ApplicationException ( "Cannot relog fillstand requests." );
					}
				}

				foreach (DataGridViewRow SelectedRow in dataGridView1.SelectedRows)
				{
					FMChannelFactory<ISites> sitesClient = new FMChannelFactory<ISites> ( );
					ISites sites = sitesClient.CreateProxy ( );

					SiteClass site = sites.Get(Security, Security.SiteGuid, false, false, false);

					SiteTimeConverter timeConverter = new SiteTimeConverter ( site );

					DataRowView Row = (DataRowView) SelectedRow.DataBoundItem;
					string transID = (string) Row["TransID"];
					TransactionDO transaction = GetTransaction ( transID );

					transaction.TransID = FuelsManagerId.NewId ( );
					transaction.Status = TransactionStatus.Requested;
					transaction.TimeIn = null;
					transaction.TimeOut = null;
					transaction.TimeEnd = null;
					transaction.RouteSchedule.FST = null;

					foreach (LineItemDO LineItem in transaction.LineItems)
					{
						LineItem.Quantity = new QuantityDO ( );

						LineItem.Status = TransactionStatus.Requested;

						foreach (SubLineItemDO sublineitem in LineItem.SubLineItems)
						{
							sublineitem.Status = TransactionStatus.Requested;
						}
					}

					transaction.TransactionDateTime = timeConverter.Now();
					transaction.RequestedDateTime = transaction.TransactionDateTime;

					SelectedRow.Selected = false;

					UndispatchTransaction ( transaction );
				}
			}
			catch (Exception except)
			{
				ErrorHandler ( except );
			}
		}

		private void CancelRequest ( object sender, EventArgs e )
		{
			try
			{
				if (Security.HasRight ( RIGHT.MODIFY_DISPATCH ) == false)
				{
					return;
				}

				// Check for completed transactions
				foreach (DataGridViewRow SelectedRow in dataGridView1.SelectedRows)
				{
					DataRowView Row = (DataRowView) SelectedRow.DataBoundItem;
					TransactionStatus status = (TransactionStatus) Row["transactionStatusInt"];

					if (status == TransactionStatus.Completed)
					{
						throw new ApplicationException ( "Completed requests cannot be cancelled." );
					}

				}

				string message = "Once an operation is canceled it cannot be un-canceled.\nAre you sure you want to cancel this job(s)?";
				DialogResult result = MessageBox.Show ( this, message, "Dispatch", MessageBoxButtons.YesNo );
				if (result == DialogResult.No)
				{
					return;
				}

				List<transactionIdAndRequestTypeType> transactionIdAndRequestTypeList = new List<transactionIdAndRequestTypeType> ( );

				// Lock on dataGridView1 to protect against changes
				lock (dataGridView1)
				{
					foreach (DataGridViewRow SelectedRow in dataGridView1.SelectedRows)
					{
						DataRowView Row = (DataRowView) SelectedRow.DataBoundItem;
						string transID = (string) Row["TransID"];
						string requesttype = (string) Row["AliasName"];

						transactionIdAndRequestTypeType transactionIdAndRequestType;
						transactionIdAndRequestType.transactionID = transID;
						transactionIdAndRequestType.requestType = requesttype;
						transactionIdAndRequestTypeList.Add ( transactionIdAndRequestType );
					}
				}

				dataGridView1.ClearSelection ( );

				foreach (transactionIdAndRequestTypeType transactionIdAndRequestType in transactionIdAndRequestTypeList)
				{
					string transID = transactionIdAndRequestType.transactionID;
					string requesttype = transactionIdAndRequestType.requestType;

					TransactionDO Transaction = GetTransaction ( transID );
					// prompt the user to enter a comment for the cancellation
					//				memoTextBox.Text=transaction.UserData["Transaction Aliases User Data 23"] as string;
					CommentForm CancelComment = new CommentForm ( );
					CancelComment.CurrentComment = Transaction.UserData["Transaction Aliases User Data 23"] as string;
					CancelComment.Forstring = "Request Type = " + requesttype;
					CancelComment.ShowDialog ( this );
					// restore the comment
					Transaction.Notes += " - " + CancelComment.CurrentComment;

					Transaction.Status = TransactionStatus.Cancelled;
					foreach (LineItemDO LineItem in Transaction.LineItems)
					{
						LineItem.Status = TransactionStatus.Cancelled;

						foreach (SubLineItemDO SubLineItem in LineItem.SubLineItems)
						{
							SubLineItem.Status = TransactionStatus.Cancelled;
						}
					}

					SaveTransaction ( Transaction );
				}
			}
			catch (Exception except)
			{
				ErrorHandler ( except );
			}
		}

