		private void vehicleComboBox_SelectedIndexChanged ( object sender, EventArgs e )
		{
			try
			{
				// Limit grid view to only this vehicle
				DataView view = (DataView) dataGridView1.DataSource;
				if (vehicleComboBox.SelectedIndex > 0)
				{
					string vehicleXREF = vehicleComboBox.Text;
					view.RowFilter = String.Format ( "XREF = '{0}'", vehicleXREF );

					// now select all the vehicle rows
					dataGridView1.SelectAll ( );

				}
				else
				{
					// when the filter is cleared the grid is deselecting all of the records
					// we need to store the current selected records so we can then restore them
					// Clear the filter
					string[] selectedTransID = new string[dataGridView1.SelectedRows.Count];
					string CurrentRowTransID = string.Empty;
					int NumberOfSelectedRows = dataGridView1.SelectedRows.Count;

					// store the current row so it can be restored
					lock (dataGridView1)
					{
						if (dataGridView1.CurrentRow != null)
						{
							DataRowView CurrentRow = (DataRowView) dataGridView1.Rows[dataGridView1.CurrentRow.Index].DataBoundItem;
							if (CurrentRow != null)
								CurrentRowTransID = (string) CurrentRow["TransID"];
						}

						for (int iLoop = 0; iLoop < NumberOfSelectedRows; iLoop++)
						{
							DataRowView Row = (DataRowView) dataGridView1.SelectedRows[iLoop].DataBoundItem;
							selectedTransID[iLoop] = (string) Row["TransID"];
						}

						view.RowFilter = string.Empty;

						// we need to set the current cell first since the grid will change the number of selections to 1 when it is set
						foreach (DataGridViewRow Row in dataGridView1.Rows)
						{
							DataRowView dataRow = (DataRowView) Row.DataBoundItem;
							if (NumberOfSelectedRows > 0)
								Row.Selected = false;
							if (!string.IsNullOrEmpty ( CurrentRowTransID ) &&
								CurrentRowTransID.Equals ( (string) dataRow["TransID"] ))
							{
								// restore the current selection
								// the only way to do this is by setting the currentcell variable since the currentrow is read only
								dataGridView1.CurrentCell = Row.Cells[0];
							}
						}

						for (int iLoop = 0; iLoop < NumberOfSelectedRows; iLoop++)
						{
							foreach (DataGridViewRow Row in dataGridView1.Rows)
							{
								DataRowView dataRow = (DataRowView) Row.DataBoundItem;
								if (dataRow != null)
								{
									if (selectedTransID[iLoop].Equals ( (string) dataRow["TransID"] ))
									{
										Row.Selected = true;

										break;
									}
								}
							}
						}
					}
				}

				RenumberGrid ( dataGridView1 );
			}
			catch (Exception except)
			{
				ErrorHandler ( except );
			}

		}

