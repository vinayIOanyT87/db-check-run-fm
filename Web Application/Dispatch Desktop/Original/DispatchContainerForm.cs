		private void RowDoubleClicked ( int RowIndex )
		{
			try
			{
				if (RowIndex >= 0)
				{
					DataRowView Row = (DataRowView) dataGridView1.Rows[RowIndex].DataBoundItem;
					if ((string) Row["AliasName"] == "Recirculation")
					{
						RecirculationForm RecirculationForm = new RecirculationForm ( );
						RecirculationForm.TransID = (string) Row["TransID"];
						RecirculationForm.ShowDialog ( this );
					}
					else
					{
						// if the transaction type is a refuel or a defuel we need to check the operational lock date and if it is before
						// that date not allow any modification if it is complete
						FuelRequestForm fuelRequestForm = new FuelRequestForm ( OperationLockDate );
						fuelRequestForm.TransID = (string) Row["TransID"];
						// if the transaction type is a refuel or a defuel we need to check the operational lock date and if it is before
						// that date not allow any modification if it is complete
						if (fuelRequestForm.transaction.Status == TransactionStatus.Completed &&
							( (string) Row["AliasName"] == "Refuel" ||
							(string) Row["AliasName"] == "Defuel" ))
						{
							DateTime CompletedDateTime = System.DateTime.UtcNow.AddYears ( -100 );
							if (Row["RequestedDateTime"].ToString ( ).Length > 0)
								CompletedDateTime = (DateTime) Row["RequestedDateTime"];

							// check the lock out date
							if (CompletedDateTime <= OperationLockDate)
							{
								MessageBox.Show ( "Can not edit completed transactions before the lock out date.\n\rEdit request ended." );
								return;
							}
						}
						fuelRequestForm.ShowDialog ( this );
					}
				}
			}
			catch (Exception except)
			{
				ErrorHandler ( except );
			}

		}

