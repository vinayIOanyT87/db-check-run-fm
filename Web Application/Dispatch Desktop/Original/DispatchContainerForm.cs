		void dataGridView1_SelectionChanged ( object sender, EventArgs e )
		{
			try
			{
				if (dataGridView1.SelectedRows.Count > 0)
				{
					SetPopupMenuEnableDisable ( );

					// Set the cancel and relog menu availability
					cancelToolStripMenuItem.Enabled = true;
					toolStripCancelButton.Enabled = true;
					relogToolStripMenuItem.Enabled = true;
					toolStripRelogButton.Enabled = true;

					lock (dataGridView1)
					{
						foreach (DataGridViewRow Row in dataGridView1.SelectedRows)
						{
							DataRowView dataRow = (DataRowView) Row.DataBoundItem;

							TransactionStatus status = (TransactionStatus) dataRow["TransactionStatusInt"];

							// if any selected transaction has a status of posted disable everything
							if (status == TransactionStatus.Posted)
							{
								cancelToolStripMenuItem.Enabled = false;
								toolStripCancelButton.Enabled = false;
								relogToolStripMenuItem.Enabled = false;
								toolStripRelogButton.Enabled = false;
								break;
							}

							if (status == TransactionStatus.Completed ||
								status == TransactionStatus.Cancelled)
							{
								cancelToolStripMenuItem.Enabled = false;
								toolStripCancelButton.Enabled = false;
								break;
							}

							short TransTypeID = (short) dataRow["TransTypeID"];
							if (TransTypeID != 4 && TransTypeID != 6)
							{
								relogToolStripMenuItem.Enabled = false;
								toolStripRelogButton.Enabled = false;
							}
						}
					}
				}
				else
				{
					cancelToolStripMenuItem.Enabled = false;
					toolStripCancelButton.Enabled = false;
					relogToolStripMenuItem.Enabled = false;
					toolStripRelogButton.Enabled = false;
				}

			}
			catch (Exception except)
			{
				ErrorHandler ( except );
			}
		}

