		void SchedulerMessageProcessScan ( )
		{
			KillEvent = new ManualResetEvent ( false );
			WaitHandle[] Events = { KillEvent };
			int WaitInterval = 100;
			int ReloadConfigCounter = 15;

			int WaitResult;
			while (0 != ( WaitResult = WaitHandle.WaitAny ( Events, WaitInterval, false ) ))
			{
				WaitInterval = 30000;	// check once every 30 seconds
				// get the scheduled events for today
				if (ReloadConfigCounter > 14)
				{
					GetTodaysScheduledEvents ( );
					ReloadConfigCounter = 0;
				}
				++ReloadConfigCounter;

				if (CheckIfAppoinmentIsDue ( ) == true)
				{
					// we do the following to ensure that the thread is safe
					ShowReminderForm ( );
				}
			}
		}

