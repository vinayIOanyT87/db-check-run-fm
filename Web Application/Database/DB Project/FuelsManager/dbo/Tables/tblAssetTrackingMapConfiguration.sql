CREATE TABLE [dbo].[tblAssetTrackingMapConfiguration]
(
	[AssetTrackingMapConfigurationGuid] UNIQUEIDENTIFIER NOT NULL, 
	[SiteGuid] UNIQUEIDENTIFIER NOT NULL,
    [MapName] NVARCHAR(100) UNIQUE NOT NULL, 
    [Zoom] INT NOT NULL, 
    [Latitude] FLOAT NOT NULL, 
    [Longitude] FLOAT NOT NULL,
    [LookupMapSourceIndex] INT NOT NULL, 
    [Description] NVARCHAR(200) NULL, 
    [Active] BIT NULL,
	[CreatedDate] DATETIMEOFFSET CONSTRAINT [DF_tblAssetTrackingMapConfiguration_CreatedDate] DEFAULT (SYSDATETIMEOFFSET()) NOT NULL, 
    [CreatedBy] [dbo].[udtUserID] CONSTRAINT [DF_tblAssetTrackingMapConfiguration_CreatedBy] DEFAULT ('') NOT NULL, 
    [UpdatedDate] DATETIMEOFFSET CONSTRAINT [DF_tblAssetTrackingMapConfiguration_UpdatedDate] DEFAULT (SYSDATETIMEOFFSET()) NOT NULL, 
    [UpdatedBy] [dbo].[udtUserID] CONSTRAINT [DF_tblAssetTrackingMapConfiguration_UpdatedBy] DEFAULT ('') NOT NULL, 
	[_RowVersion] ROWVERSION NOT NULL,
    [_ClusterIdx] BIGINT IDENTITY (1, 1) NOT NULL,
    CONSTRAINT [PK_tblAssetTrackingMapConfiguration] PRIMARY KEY NONCLUSTERED ([AssetTrackingMapConfigurationGuid]),
	CONSTRAINT [FK_tblAssetTrackingMapConfiguration_LookupMapSourceIndex] FOREIGN KEY ([LookupMapSourceIndex]) REFERENCES [lookup].[tblMapSource] ([MapSourceIndex]),
	CONSTRAINT [CK_tblAssetTrackingMapConfiguration_Uniqueness] CHECK ([dbo].[udf_CheckUniquenessAssetTrackingMapConfiguration]([AssetTrackingMapConfigurationGuid],[SiteGuid],[MapName])=(1)),
	CONSTRAINT [FK_tblAssetTrackingMapConfiguration_SiteGuid] FOREIGN KEY ([SiteGuid]) REFERENCES [dbo].[tblSites] ([SiteGuid])
);

GO
CREATE UNIQUE CLUSTERED INDEX [IX_tblAssetTrackingMapConfiguration_ClusterIdx]
    ON [dbo].[tblAssetTrackingMapConfiguration]([_ClusterIdx] ASC);

