			source.MeterStartDateTime,
			source.FreezePoint,
			source.DifferentialPressure,
			source.DosageRate,
			source.DeleteFlag,
			source.PresetAmount,
			source.StorageLocationID,
			source.MeterID,
			source.COAID,
			source.TransactionInventoryDate,
			source.Tax1,
			source.Tax2,
			source.Tax3,
			source.Tax4,
			source.Tax5,
			source.TransVersion,
			source.ImproperAdditization,
			source.BrokenBlend,
			source.Flag01,
			source.Flag02,
			source.Flag03,
			source.Flag04,
			source.Flag05,
			source.Flag06,
			source.Number01,
			source.Number02,
			source.Number03,
			source.Number04,
			source.Number05,
			source.Number06,
			source.Date01,
			source.Date02,
			source.Date03,
			source.Date04,
			source.MassQuantity,
			source.NetManualValueFlag,
			source.GrossManualValueFlag,
			source.MassManualValueFlag,
			source.VcfManualValueFlag,
			source.DeliveredGrossManualValueFlag,
			source.DeliveredNetManualValueFlag,
			source.LookupTransactionStatusIndex,
			source.LookupQualityIndex,
			source.ProductGuid,
			source.StorageLocationTankGuid,
			source.MeterGuid,
			source.PackageManualValueFlag,
			source.CleanLineItem,
			source.CleanLineDeductItem,
			source.CleanLineDeductQuantity,
			source.CleanLinePackQuantity,
			SYSDATETIMEOFFSET(), --CreatedDate
