			Flag02 = source.Flag02,
			Flag03 = source.Flag03,
			Flag04 = source.Flag04,
			Flag05 = source.Flag05,
			Flag06 = source.Flag06,
			Number01 = source.Number01,
			Number02 = source.Number02,
			Number03 = source.Number03,
			Number04 = source.Number04,
			Number05 = source.Number05,
			Number06 = source.Number06,
