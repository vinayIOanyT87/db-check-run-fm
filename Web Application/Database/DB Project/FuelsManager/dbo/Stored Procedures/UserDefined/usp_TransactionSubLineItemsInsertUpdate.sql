				LookupQualityIndex,
				ProductGuid,
				StorageLocationTankGuid,
				MeterGuid,
				PackageManualValueFlag,
				CleanLineItem,
				CleanLineDeductItem,
				CleanLineDeductQuantity,
				CleanLinePackQuantity,
				CreatedUpdatedBy
			FROM @TransactionSubLineItems
			) AS source
		ON source.TransactionSubLineItemGuid = target.TransactionSubLineItemGuid
		WHEN MATCHED THEN UPDATE SET
			SequenceID = source.SequenceID,
			Product = source.Product,
			ProductCode = source.ProductCode,
			ProductType = source.ProductType,
			GrossQuantity = source.GrossQuantity,
			DeliveredGrossQuantity = source.DeliveredGrossQuantity,
			NetQuantity = source.NetQuantity,
			DeliveredNetQuantity = source.DeliveredNetQuantity,
			Vcf = source.Vcf,
			Pressure = source.Pressure,
			Density = source.Density,
			Temperature = source.Temperature,
			Customs = source.Customs,
			ArmNumber = source.ArmNumber,
			LineNumber = source.LineNumber,
			BatchNumber = source.BatchNumber,
			LineFill = source.LineFill,
			BottomVolume = source.BottomVolume,
			NetCapacity = source.NetCapacity,
			TankStatus = source.TankStatus,
			MeterFactor = source.MeterFactor,
			MeterStart = source.MeterStart,
			MeterStop = source.MeterStop,
			MeterStopDateTime = source.MeterStopDateTime,
			MeterStartDateTime = source.MeterStartDateTime,
			FreezePoint = source.FreezePoint,
			DifferentialPressure = source.DifferentialPressure,
			DosageRate = source.DosageRate,
			DeleteFlag = source.DeleteFlag,
