			CleanLineDeductItem,
			CleanLineDeductQuantity,
			CleanLinePackQuantity,
			CreatedDate,
			CreatedBy,
			UpdatedDate,
			UpdatedBy
		)
		VALUES
		(
			source.TransactionSubLineItemGuid,
			source.TransactionLineItemGuid,
			source.TransactionGuid,
			source.SequenceID,
			source.Product,
			source.ProductCode,
			source.ProductType,
			source.GrossQuantity,
			source.DeliveredGrossQuantity,
			source.NetQuantity,
			source.DeliveredNetQuantity,
			source.Vcf,
			source.Pressure,
			source.Density,
			source.Temperature,
			source.Customs,
			source.ArmNumber,
