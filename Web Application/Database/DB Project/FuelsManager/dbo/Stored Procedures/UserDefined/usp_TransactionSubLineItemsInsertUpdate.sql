			MeterGuid = source.MeterGuid,
			PackageManualValueFlag = source.PackageManualValueFlag,
			CleanLineItem = source.CleanLineItem,
			CleanLineDeductItem = source.CleanLineDeductItem,
			CleanLineDeductQuantity = source.CleanLineDeductQuantity,
			CleanLinePackQuantity = source.CleanLinePackQuantity,
			UpdatedDate = SYSDATETIMEOFFSET(),
			UpdatedBy = source.CreatedUpdatedBy
		WHEN NOT MATCHED THEN INSERT 
		(
			TransactionSubLineItemGuid,
			TransactionLineItemGuid,
			TransactionGuid,			
			SequenceID,
			Product,
			ProductCode,
			ProductType,
			GrossQuantity,
			DeliveredGrossQuantity,
			NetQuantity,
			DeliveredNetQuantity,
			Vcf,
			Pressure,
			Density,
			Temperature,
			Customs,
			ArmNumber,
			LineNumber,
			BatchNumber,
			LineFill,
			BottomVolume,
			NetCapacity,
			TankStatus,
			MeterFactor,
			MeterStart,
			MeterStop,
			MeterStopDateTime,
			MeterStartDateTime,
			FreezePoint,
			DifferentialPressure,
			DosageRate,
			DeleteFlag,
			PresetAmount,
			StorageLocationID,
			MeterID,
			COAID,
			TransactionInventoryDate,
			Tax1,
			Tax2,
			Tax3,
			Tax4,
			Tax5,
			TransVersion,
			ImproperAdditization,
			BrokenBlend,
			Flag01,
			Flag02,
			Flag03,
			Flag04,
			Flag05,
			Flag06,
			Number01,
			Number02,
			Number03,
			Number04,
			Number05,
