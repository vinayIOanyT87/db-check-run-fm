			MeterID = source.MeterID,
			COAID = source.COAID,
			TransactionInventoryDate = source.TransactionInventoryDate,
			Tax1 = source.Tax1,
			Tax2 = source.Tax2,
			Tax3 = source.Tax3,
			Tax4 = source.Tax4,
