				TransactionLineItemGuid,
				TransactionGuid,			
				SequenceID,
				Product,
				ProductCode,
				ProductType,
				GrossQuantity,
				DeliveredGrossQuantity,
				NetQuantity,
				DeliveredNetQuantity,
				Vcf,
