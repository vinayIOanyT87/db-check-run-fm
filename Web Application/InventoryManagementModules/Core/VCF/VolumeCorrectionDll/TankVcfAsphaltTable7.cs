        public override bool TemperatureCorr(double dDensity,
                                            double dMeasTemp,
                                            double dStdTempInC,
                                            double dStdTemp,
                                            EngineeringUnit bDensityUnits,
                                            EngineeringUnit bTempUnits,
                                            double dDensityPress,			// density pressure for api 2004
                                            EngineeringUnit bDensityPressUnits,	// density pressure units for api 2004
                                            double dAlternateTemperature,	// selected refined product sub catagory for api 2004
                                            double dBaseTemp,	// api 2004 alternate base temp reference
                                            double dAlternateBasePress,	// api 2004 alternate base pressure reference
                                            ref double[] dK,
                                            ref double pdVcfc,
                                            ref int piFlag,
												ref double CTLReturn,
												ref double CPLReturn,
											bool RangeCk,
                                            bool bRound,
                                            bool bTable60,				//	Optional
                                            bool UseDensity)                //	Optional
        {
            double TemperatureInF = 0.0;
            double StdDensityInapi = 0.0;
            double dVCFTemp = 0.0;
            int iDensityGroup;
            // temporary code to verify the data table
            // run the following if the header file is modified.
            // if you hit the return false then you have an entry out of order
            /*	for(int x = 1;x <=500;x++)//temperature
                {
                    for(int y=0;y<=7;y++)//groups
                    {
                        if(Asphalt_table7_Lookup[x].dVCF[y] >= 0.0 &&
                            Asphalt_table7_Lookup[x-1].dVCF[y] >= 0.0)
                        {
                            if(Asphalt_table7_Lookup[x].dVCF[y] >= Asphalt_table7_Lookup[x-1].dVCF[y])
                            {
                                return false;
                            }
                        }
                    }
                }
            */
            // calculations are based on std density so if density is selected fail the calculation
            if (UseDensity)
            {
                piFlag = SET_APICORR_ALARM;
                return false;
            }

            // convert the density to api
            if (!ConvertEngUnits.ConvEngrUnits(ref StdDensityInapi, dDensity, EngineeringUnit.FmdDegApi, bDensityUnits, 0))
            {
                piFlag = SET_APICORR_ALARM;
                return false;
            }

            // round the std density to 1 decimal point
            RoundDouble(StdDensityInapi, ref StdDensityInapi, 1, false, false);

            // do range check on density
            if (StdDensityInapi > MAX_APIF ||
                StdDensityInapi < MIN_APIF)
            {
                piFlag = SET_APICORR_ALARM;
                return false;
            }

            // convert temperature to F
            if (!ConvertEngUnits.ConvEngrUnits(ref TemperatureInF, dMeasTemp, EngineeringUnit.FmtDegF, bTempUnits, 0))
            {
                piFlag = SET_APICORR_ALARM;
                return false;
            }

            // do range check on temperature
            if (TemperatureInF < MIN_TEMPF ||
                TemperatureInF > MAX_TEMPF)
            {
                piFlag = SET_APICORR_ALARM;
                return false;
            }

            // determine the density group to use based on api
            if (StdDensityInapi >= GROUP0_MIN &&
                StdDensityInapi <= GROUP0_MAX)
                iDensityGroup = GROUP0;
            else if (StdDensityInapi >= GROUP1_MIN &&
                    StdDensityInapi <= GROUP1_MAX)
                iDensityGroup = GROUP1;
            else if (StdDensityInapi >= GROUP2_MIN &&
                    StdDensityInapi <= GROUP2_MAX)
                iDensityGroup = GROUP2;
            else if (StdDensityInapi >= GROUP3_MIN &&
                    StdDensityInapi <= GROUP3_MAX)
                iDensityGroup = GROUP3;
            else if (StdDensityInapi >= GROUP4_MIN &&
                    StdDensityInapi <= GROUP4_MAX)
                iDensityGroup = GROUP4;
            else if (StdDensityInapi >= GROUP5_MIN &&
                    StdDensityInapi <= GROUP5_MAX)
                iDensityGroup = GROUP5;
            else if (StdDensityInapi >= GROUP6_MIN &&
                    StdDensityInapi <= GROUP6_MAX)
                iDensityGroup = GROUP6;
            else if (StdDensityInapi >= GROUP7_MIN &&
                    StdDensityInapi <= GROUP7_MAX)
                iDensityGroup = GROUP7;
            else
            {
                piFlag = SET_APICORR_ALARM;
                return false;
            }

            // determine the VCF
            dVCFTemp = -1.0;
            for (int iLoop = MIN_TEMPF; iLoop < MAX_TEMPF; iLoop++)
            {
                // first check for a direct match
                if (TemperatureInF == Asphalt_table7_Lookup[iLoop].fTemp)
                {
                    dVCFTemp = Asphalt_table7_Lookup[iLoop].dVCF[iDensityGroup];
                    break;
                }
                // check for match on the next point
                else if (TemperatureInF == Asphalt_table7_Lookup[iLoop + 1].fTemp)
                {
                    dVCFTemp = Asphalt_table7_Lookup[iLoop + 1].dVCF[iDensityGroup];
                    break;
                }
                // check for scaling between points
                else if (TemperatureInF > Asphalt_table7_Lookup[iLoop].fTemp &&
                    TemperatureInF < Asphalt_table7_Lookup[iLoop + 1].fTemp)
                {
                    dVCFTemp = ScaleBetweenPoints(Asphalt_table7_Lookup[iLoop].fTemp,
                                                            Asphalt_table7_Lookup[iLoop + 1].fTemp,
                                                            Asphalt_table7_Lookup[iLoop].dVCF[iDensityGroup],
                                                            Asphalt_table7_Lookup[iLoop + 1].dVCF[iDensityGroup],
                                                            TemperatureInF);
                    break;
                }
            }
            if (dVCFTemp < 0) // denotes outside of table range for density group
            {
                piFlag = SET_APICORR_ALARM;
                return false;
            }
            pdVcfc = dVCFTemp;
            return true;
        }

        protected double ScaleBetweenPoints(double dBaseMin,
                                                                            double dBaseMax,
                                                                            double dValueMin,
                                                                            double dValueMax,
                                                                            double dBaseValue)
        {
            double dReturn = 0.0;
            double dRatio = 0.0;

            dRatio = (dBaseValue - dBaseMin) / (dBaseMax - dBaseMin);

            dReturn = (dRatio * (dValueMax - dValueMin)) + dValueMin;

            return dReturn;
        }

