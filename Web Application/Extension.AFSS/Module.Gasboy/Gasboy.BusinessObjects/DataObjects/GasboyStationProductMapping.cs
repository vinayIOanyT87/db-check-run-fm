namespace FuelsManager.Afss.Module.Gasboy.BusinessObjects.DataObjects
{
    using System;
    using System.ComponentModel.DataAnnotations;
    using System.Data;
    using System.Data.SqlClient;
    using System.Runtime.Serialization;
    using FMBusinessObjects.DataObjects;

    /// <summary>
    /// Represents a mapping between a product defined at a Gasboy Station and a product defined in FuelsManager
    /// </summary>
    [DataContract]
    [Serializable]
    public class GasboyStationProductMapping : BaseDataObject
    {
        /// <summary>
        /// The ID of the product generated by the external station
        /// </summary>
        [Required(ErrorMessage = "You must provide the Station Product ID")]
        public override string ID
        {
            get
            {
                return base.ID;
            }

            set
            {
                base.ID = value;
            }
        }

        /// <summary>
        /// The ID of the FuelsManager product that the external station product corresponds to
        /// </summary>
        [DataMember]
        public string FuelsManagerProductID { get; set; }

        /// <summary>
        /// Identifies the FuelsManager product that the external station product corresponds to
        /// </summary>
        [Required(ErrorMessage = "You must select a FuelsManager Product")]
        [DataMember]
        public Guid FuelsManagerProductMasterRecordGuid { get; set; }

        /// <summary>
        /// Identifies the Gasboy Station that this product mapping belongs to
        /// </summary>
        [DataMember]
        public Guid ExternalStationGuid { get; set; }

        /// <summary>
        /// Return the values in the Gasboy Station product Mapping to their original values
        /// </summary>
        public override void Reset()
        {
            base.Reset();
            this.FuelsManagerProductID = string.Empty;
            this.FuelsManagerProductMasterRecordGuid = Guid.Empty;
            this.ExternalStationGuid = Guid.Empty;
        }
    }
}
